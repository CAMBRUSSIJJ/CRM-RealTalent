#!/usr/bin/env bash
# RealTalent Garimpo: reuse the existing local Firecrawl + Ollama installation.
# No rebuild, reinstall, volume removal, schema changes or paid cloud services.
# Run as: bash ~/Downloads/INICIAR-GARIMPO-LOCAL.sh
set -u

say() { printf '\n%s\n' "$*"; }
fail() { printf 'ERRO: %s\n' "$*" >&2; return 1; }

say "===== GARIMPO REALTALENT — MODO LINUX LOCAL ====="

for tool in docker curl node python3; do
  command -v "$tool" >/dev/null 2>&1 || { fail "Instale $tool antes de continuar."; exit 1; }
done
docker info >/dev/null 2>&1 || { fail "Docker não está acessível. Inicie o Docker primeiro."; exit 1; }
curl -fsS --max-time 8 http://127.0.0.1:11434/api/tags >/dev/null 2>&1 ||
  { fail "Ollama não está respondendo em 127.0.0.1:11434. Inicie o Ollama."; exit 1; }
echo "✓ Ollama local acessível."

# Recognize the installer generated by the authenticated RealTalent CRM.
CONFIG=""
for file in "$HOME"/Downloads/RealTalent-Garimpo-Conexao-*/deploy/local-garimpo/garimpo.env; do
  if [[ -f "$file" ]]; then
    if [[ -n "$CONFIG" ]]; then
      fail "Mais de uma instalação encontrada em Downloads. Preserve as pastas e identifique a instalação ativa."
      exit 1
    fi
    CONFIG="$file"
  fi
done
[[ -n "$CONFIG" ]] || { fail "Conector existente não encontrado. Conecte o Linux pelo CRM antes de iniciar."; exit 1; }
CONNECTOR="$(dirname "$CONFIG")"
[[ -f "$CONNECTOR/bridge.mjs" ]] || { fail "O conector bridge.mjs não existe em $CONNECTOR."; exit 1; }
[[ -d "$CONNECTOR/node_modules" ]] || { fail "Dependências do conector ausentes. Use o configurador original uma vez."; exit 1; }

# Switch back from a previously configured remote gateway if necessary.
# Changes only FIRECRAWL_API_URL and FIRECRAWL_API_KEY. Back up with mode 600.
python3 - "$CONFIG" <<'PY'
from datetime import datetime
from pathlib import Path
import os
import re
import shutil
import sys
import tempfile

path = Path(sys.argv[1])
old = path.read_text(encoding="utf-8")
if not re.search(r"(?m)^GARIMPO_CONNECTOR_TOKEN=[a-f0-9]{64}$", old):
    raise SystemExit("ERRO: credencial existente inválida. Gere uma nova conexão no CRM; nada foi alterado.")
remove = ("FIRECRAWL_API_URL=", "FIRECRAWL_API_KEY=")
newlines = [line for line in old.splitlines() if not line.startswith(remove)]
updated = "\n".join(newlines + ["FIRECRAWL_API_URL=http://127.0.0.1:3002"]) + "\n"
if old != updated:
    backup = path.with_name("garimpo.env.backup-local-" + datetime.now().strftime("%Y%m%d-%H%M%S"))
    shutil.copy2(path, backup)
    os.chmod(backup, 0o600)
    fd, tmp = tempfile.mkstemp(prefix=".garimpo-local-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(updated)
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)
    print("✓ Firecrawl configurado para 127.0.0.1:3002. Backup privado preservado.")
else:
    print("✓ Firecrawl já configurado para 127.0.0.1:3002.")
PY
[[ "$?" -eq 0 ]] || { fail "Não foi possível verificar o arquivo privado. Conector não iniciado."; exit 1; }

# Start only containers that are stopped, in dependency order.
start_existing() {
  local name="$1"
  if ! docker inspect "$name" >/dev/null 2>&1; then
    fail "Contêiner ausente: $name. Não vou criar outra instalação."
    return 1
  fi
  local state
  state="$(docker inspect -f '{{.State.Running}}' "$name" 2>/dev/null)"
  if [[ "$state" == "true" ]]; then
    printf '✓ %s já está ativo\n' "$name"
    return 0
  fi
  printf 'Iniciando %s ...\n' "$name"
  docker start "$name" >/dev/null || { fail "Não foi possível iniciar $name"; return 1; }
}

say "===== VERIFICANDO SERVIÇOS EXISTENTES ====="
for suffix in redis rabbitmq nuq-postgres searxng playwright-service; do
  start_existing "realtalent-garimpo-${suffix}-1" || exit 1
done

# Do not start Firecrawl workers before the database is healthy.
DB="realtalent-garimpo-nuq-postgres-1"
healthy="false"
for attempt in $(seq 1 25); do
  state="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$DB" 2>/dev/null)"
  if [[ "$state" == "healthy" || "$state" == "running" ]]; then
    healthy="true"
    break
  fi
  sleep 2
done
[[ "$healthy" == "true" ]] || { fail "PostgreSQL não ficou saudável. Consulte docker logs --tail 30 $DB."; exit 1; }
start_existing realtalent-garimpo-api-1 || exit 1

say "===== VALIDANDO FIRECRAWL ====="
ok="false"
for attempt in $(seq 1 25); do
  if curl -fsS --max-time 5 http://127.0.0.1:3002/ >/dev/null 2>&1; then
    ok="true"
    break
  fi
  sleep 2
done
[[ "$ok" == "true" ]] || {
  fail "API Firecrawl ainda não responde. Confira docker logs --tail 40 realtalent-garimpo-api-1."
  exit 1
}
echo "✓ Firecrawl local: HTTP 200."
WORKERS="$(docker inspect --format '{{range .Config.Env}}{{println .}}{{end}}' realtalent-garimpo-api-1 | grep '^NUQ_WORKER_COUNT=' | head -1)"
echo "${WORKERS:-Aviso: NUQ_WORKER_COUNT não definido; confira o perfil econômico.}"
echo "✓ Nenhum recurso no Railway foi necessário."

say "===== CONECTANDO AO CRM ====="
# Never start a second connector that could compete for the same queued jobs.
if ps -eo args= | grep -E '(^|[ /])node[[:space:]]+([^ ]*/)?bridge\.mjs([[:space:]]|$)' | grep -v grep >/dev/null 2>&1; then
  echo "✓ Conector do CRM já está em execução. Não iniciarei outra cópia."
  echo "Abra o CRM > Garimpo e confira 'Linux conectado'."
  exit 0
fi

echo "✓ Abrindo conector existente. Mantenha este terminal aberto para pesquisar no CRM."
echo "Para encerrar o conector: Ctrl+C (isso não desliga o Firecrawl)."
cd -- "$CONNECTOR" || exit 1
exec node bridge.mjs "$CONFIG"
