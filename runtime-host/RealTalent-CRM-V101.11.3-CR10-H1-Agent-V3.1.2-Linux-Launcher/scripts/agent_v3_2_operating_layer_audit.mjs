import fs from 'node:fs'
import path from 'node:path'
const root=process.cwd(); const read=(p)=>fs.readFileSync(path.join(root,p),'utf8')
const checks=[]; const add=(name,ok)=>checks.push({name,ok:Boolean(ok)})
const registry=read('src/services/realtalent-crm-capabilities.ts')
const executor=read('src/services/realtalent-crm-capability-executor.ts')
const provider=read('src/services/realtalent-assistant-provider.ts')
const drawer=read('src/features/assistant/assistant-drawer.tsx')
const ids=[...registry.matchAll(/id: '([^']+)'/g)].map(m=>m[1])
add('>=58 native capabilities', ids.length>=58)
add('unique capability ids', new Set(ids).size===ids.length)
for(const id of ['notifications.dismiss_all','crm.query','agent.undo_last','leads.create','pipeline.create_stage','tasks.create','calendar.create','calls.log_outcome','communications.send_email','proposals.create','teams.invite','revenue.create']) add(id, ids.includes(id))
add('permission engine', executor.includes('ensurePermission(runtime, step)'))
add('record scope', executor.includes('assertRecordAccess(runtime'))
add('sensitive fields', executor.includes('assertSensitiveCapabilityField'))
add('transaction undo', executor.includes('undoCrmAgentOperation'))
add('official email/whatsapp', executor.includes('sendOfficialEmail')&&executor.includes('sendOfficialWhatsApp'))
add('universal query', executor.includes("step.capabilityId === 'crm.query'"))
add('provider routes unknown to capabilities', provider.includes("semantic.interpretation.intent !== 'unknown'"))
add('read auto execute', drawer.includes("steps.every((step) => step.risk === 'read')"))
add('risk confirmation', drawer.includes("Revisar e executar"))
for(const c of checks) console.log(`${c.ok?'PASS':'FAIL'} ${c.name}`)
const failed=checks.filter(c=>!c.ok); console.log(`V3.2 CRM AUDIT ${checks.length-failed.length}/${checks.length} passed`); if(failed.length)process.exit(1)
