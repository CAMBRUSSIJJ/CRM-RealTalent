import fs from 'node:fs'
import { spawnSync } from 'node:child_process'
const read=p=>fs.readFileSync(p,'utf8')
const pkg=JSON.parse(read('package.json'))
const runtimePkg=JSON.parse(read('runtime/communications/package.json'))
const launcher=read('scripts/start.mjs')
const helper=read('scripts/communications-runtime-deps.mjs')
const qr=read('scripts/whatsapp-qr-bridge.mjs')
const browser=read('scripts/whatsapp-browser-qr-bridge.mjs')
const checks=[]; const ok=(n,v)=>{checks.push([n,Boolean(v)]);console.log(`${v?'OK  ':'FAIL'} ${n}`)}
const lock=spawnSync(process.execPath,['scripts/lockfile-integrity.mjs','--quiet'],{encoding:'utf8'})
ok('lockfile principal sincronizado',lock.status===0)
ok('core não carrega Baileys',!pkg.dependencies?.['@whiskeysockets/baileys'])
ok('core não carrega qrcode',!pkg.dependencies?.qrcode)
ok('core não carrega whatsapp-web.js',!pkg.dependencies?.['whatsapp-web.js'])
ok('runtime fixa Baileys',runtimePkg.dependencies?.['@whiskeysockets/baileys']==='7.0.0-rc14')
ok('runtime fixa qrcode',runtimePkg.dependencies?.qrcode==='1.5.4')
ok('runtime fixa whatsapp-web.js',runtimePkg.dependencies?.['whatsapp-web.js']==='1.34.7')
ok('launcher separa dependências core e comunicação',launcher.includes('ensureCommunicationsRuntimeDependencies')&&launcher.includes('coreDepsPresent'))
ok('runtime isolado não altera package-lock principal',read('scripts/install-communications-runtime-deps.mjs').includes("'--package-lock=false'"))
ok('QR Baileys usa import isolado',qr.includes("importCommunicationsPackage('@whiskeysockets/baileys')"))
ok('QR renderer usa runtime isolado',browser.includes("importCommunicationsPackage('qrcode')"))
ok('WhatsApp Web usa runtime isolado',browser.includes("importCommunicationsPackage('whatsapp-web.js')"))
ok('helper resolve a partir de runtime/communications',helper.includes("'runtime', 'communications'"))
ok('doctor distingue core de Comunicação',launcher.includes('Dependências core:')&&launcher.includes('Runtime Comunicação:'))
ok('URL preserva marker CR1',launcher.includes('rt_readiness=101.11.3-cr1-build-dependency-closure')||launcher.includes('rt_cr1=101.11.3-cr1-build-dependency-closure'))
ok('script CR1 registrado',pkg.scripts?.['qa:commercial-readiness:cr1']==='node scripts/commercial_readiness_cr1_build_dependency_closure_audit.mjs')
const failed=checks.filter(([,v])=>!v)
console.log(`\nCR1 Build & Dependency Closure: ${checks.length-failed.length}/${checks.length}`)
if(failed.length)process.exit(1)
