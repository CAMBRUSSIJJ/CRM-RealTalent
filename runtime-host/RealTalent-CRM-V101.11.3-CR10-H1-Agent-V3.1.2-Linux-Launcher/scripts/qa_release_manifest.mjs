import fs from 'node:fs'
import path from 'node:path'
const root=process.cwd(); const read=p=>fs.readFileSync(path.join(root,p),'utf8'); const exists=p=>fs.existsSync(path.join(root,p))
const manifest=JSON.parse(read('release-manifest.json')); const pkg=JSON.parse(read('package.json')); const lock=JSON.parse(read('package-lock.json')); const health=JSON.parse(read('public/health.json')); const runtime=JSON.parse(read('public/runtime-version.json')); const migrations=JSON.parse(read('supabase/migrations.lock.json'))
const expected=manifest.release.version; const labels=[]; const check=(label,ok)=>labels.push({label,ok:Boolean(ok)})
check('manifest version = package',pkg.version===expected)
check('package-lock version',lock.version===expected&&lock.packages?.['']?.version===expected)
check('VERSION',read('VERSION').trim()===`V${expected}`)
check('APP_VERSION',read('src/lib/app-version.ts').includes(`APP_VERSION = '${expected}'`))
check('health/runtime version',health.version===expected&&runtime.version===expected)
check('release channel',health.release===manifest.release.channel&&runtime.channel===manifest.release.channel)
check('migration count',migrations.migrations.length===manifest.migrations.expectedCount)
check('capability matrix existe',exists(manifest.capabilityMatrix))
check('browser flow catalog existe',exists(manifest.browserFlows))
check('default gate existe',Boolean(pkg.scripts?.[manifest.qa.defaultGate]))
check('legacy gate existe',Boolean(pkg.scripts?.[manifest.qa.legacyGate]))
for(const gate of manifest.qa.requiredGates) check(`required gate ${gate}`,Boolean(pkg.scripts?.[gate]))
for(const item of labels) console.log(`${item.ok?'OK  ':'FAIL'} ${item.label}`)
const failed=labels.filter(x=>!x.ok);console.log(`\nRelease Manifest: ${labels.length-failed.length}/${labels.length} invariantes.`);if(failed.length)process.exit(1)
