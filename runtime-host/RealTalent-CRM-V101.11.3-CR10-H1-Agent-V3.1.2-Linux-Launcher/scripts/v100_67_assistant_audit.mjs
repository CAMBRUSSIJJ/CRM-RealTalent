import fs from 'node:fs'
import path from 'node:path'
import { auditRuntimeDependencies } from './runtime-dependency-policy.mjs'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const has = (file, needle) => read(file).includes(needle)
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })
const pkg = JSON.parse(read('package.json'))
const service = read('src/services/realtalent-assistant.ts')
const provider = read('src/services/realtalent-assistant-provider.ts')
const drawer = read('src/features/assistant/assistant-drawer.tsx')
const topbar = read('src/components/layout/topbar.tsx')
const calls = read('src/features/calls/calls-page.tsx')

const versionParts = pkg.version.split('.').map(Number)
check('package preserva V100.67+', versionParts[0] > 100 || (versionParts[0] === 100 && versionParts[1] >= 67))
check('APP_VERSION acompanha pacote', has('src/lib/app-version.ts', `APP_VERSION = '${pkg.version}'`))
check('health acompanha pacote', has('public/health.json', pkg.version))
check('title acompanha pacote', has('index.html', `V${pkg.version}`))
check('bridge território acompanha pacote', has('src/features/commercial-map/commercial-map-page.tsx', 'version: APP_VERSION'))
check('sem dependência runtime não aprovada', auditRuntimeDependencies(Object.keys(pkg.dependencies ?? {})).ok)
check('sem migration V100.67', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => name.includes('v100_67')))
check('assistant service existe', fs.existsSync(path.join(root, 'src/services/realtalent-assistant.ts')))
check('provider adapter existe', fs.existsSync(path.join(root, 'src/services/realtalent-assistant-provider.ts')))
check('provider não envia dados externamente', provider.includes('sendsDataExternally: false'))
check('provider sem autoridade de persistência', !provider.includes('createActivity(') && !provider.includes('updateLead('))
check('intent priorities', service.includes("| 'priorities'"))
check('intent risk_deals', service.includes("| 'risk_deals'"))
check('intent call_now', service.includes("| 'call_now'"))
check('intent proposal_followup', service.includes("| 'proposal_followup'"))
check('intent missing_decision_maker', service.includes("| 'missing_decision_maker'"))
check('intent stale_deals', service.includes("| 'stale_deals'"))
check('intent forecast', service.includes("| 'forecast'"))
check('intent lead_summary', service.includes("| 'lead_summary'"))
check('intent create_followups', service.includes("| 'create_followups'"))
check('grounding Deal Intelligence', service.includes('buildDealPortfolio') && service.includes('buildDealIntelligence'))
check('forecast usa Revenue Intelligence ou predictedValue', service.includes('calculateRevenueIntelligence') || service.includes('portfolio.predictedValue'))
check('risco usa portfolio', service.includes("intent === 'risk_deals'"))
check('ligações respeitam DNC', service.includes('!deal.lead.doNotContact'))
check('decisor usa risk engine', service.includes("risk.key === 'missing-decision-maker'"))
check('propostas usa status sent/viewed', service.includes("['sent', 'viewed'].includes"))
check('resumo identifica lead', service.includes('findLeadForSummary'))
check('follow-up usa contexto anterior', service.includes('context.previousLeadIds'))
check('follow-up exclui DNC', service.includes("lead.status === 'active' && !lead.doNotContact"))
check('follow-up gera plano, não mutação', service.includes("kind: 'create_followups'") && service.includes('Nenhuma alteração foi aplicada ainda'))
check('parser de amanhã', service.includes("query.includes('amanha')"))
check('parser de horário', service.includes('hourMatch'))
check('drawer global existe', fs.existsSync(path.join(root, 'src/features/assistant/assistant-drawer.tsx')))
check('drawer lazy loaded', topbar.includes("lazy(() => import('../../features/assistant/assistant-drawer')"))
check('atalho Ctrl/Cmd+J', topbar.includes("event.key.toLowerCase() === 'j'"))
check('botão no topbar', topbar.includes('RealTalent Assistant') && (topbar.includes('global-appbar-v10162__assistant') || topbar.includes('Abrir RealTalent Assistant')))
check('aviso de privacidade', drawer.includes('Nenhum dado é enviado para IA externa'))
check('usa provider adapter/gateway', drawer.includes('localDeterministicAssistantProvider.answer') || drawer.includes('realTalentAiGateway.answer'))
check('prévia obrigatória', drawer.includes('Revisar e executar'))
check('confirmação antes da execução', drawer.includes('confirmAction'))
check('execução usa AppActions', drawer.includes('createActivities'))
check('revalida lead ativo', drawer.includes("lead.status !== 'active'"))
check('revalida DNC', drawer.includes('lead.doNotContact'))
check('previne follow-up duplicado próximo', drawer.includes("activity.type === 'followup'") && drawer.includes('12 * 60 * 60_000'))
check('origem auditável assistant', drawer.includes("purpose: 'assistant-followup'"))
check('navega para Deal Inspector', drawer.includes("action: 'deal-inspector'"))
check('navega para Proposal 360', drawer.includes('proposalId: item.proposalId'))
check('navega para Account 360', drawer.includes("action: 'account360'"))
check('deep link de ligação', drawer.includes("action: 'start-call'"))
check('Calls consome start-call', calls.includes("routeContext.action !== 'start-call'"))
check('Calls limpa route context', calls.includes("clearRouteContext(['leadId', 'action'])"))
check('CSS dedicado', fs.existsSync(path.join(root, 'src/styles/realtalent-assistant-v10067.css')))
check('teste unitário dedicado', fs.existsSync(path.join(root, 'src/services/realtalent-assistant.test.ts')))
check('release notes', fs.existsSync(path.join(root, 'RELEASE_NOTES_V100.67.0.md')))
check('documentação dedicada', fs.existsSync(path.join(root, 'docs/V100.67.0-REALTALENT-ASSISTANT.md')))
check('npm check inclui V100.67', String(pkg.scripts['check:legacy']).includes('qa:v100.67.0'))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'OK' : 'FAIL'} ${item.name}`)
if (failed.length) {
  console.error(`\nV100.67 audit falhou: ${failed.length}/${checks.length}`)
  process.exit(1)
}
console.log(`\nV100.67 RealTalent Assistant: ${checks.length}/${checks.length} contratos aprovados.`)
