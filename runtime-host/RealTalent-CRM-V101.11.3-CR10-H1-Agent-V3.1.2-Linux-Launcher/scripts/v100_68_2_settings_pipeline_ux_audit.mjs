import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const version = read('src/lib/app-version.ts')
const prefs = read('src/features/pipeline/pipeline-preferences.ts')
const pipeline = read('src/features/pipeline/pipeline-page.tsx')
const dealCss = read('src/styles/deal-intelligence-v10062.css')
const settings = read('src/features/settings/settings-page.tsx')
const settingsCss = read('src/styles/settings-v100.css')
const uxConsolidation = exists('src/styles/interaction-ui.css')

const versionParts = String(pkg.version).split('.').map(Number)
const isAtLeast100682 = versionParts[0] > 100 || (versionParts[0] === 100 && (versionParts[1] > 68 || (versionParts[1] === 68 && versionParts[2] >= 2)))
check('base V100.68.2 preservada', isAtLeast100682 && version.includes('BACKUP_SCHEMA_VERSION'))
check('backup schema preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('preferência intelligenceCollapsed tipada', prefs.includes('intelligenceCollapsed: boolean'))
check('fallback preserva comportamento histórico ou evolução consolidada', prefs.includes('intelligenceCollapsed: false') || (uxConsolidation && prefs.includes('intelligenceCollapsed: true')))
check('load normaliza preferência antiga ou respeita false explícito na evolução', prefs.includes('parsed.intelligenceCollapsed === true') || (uxConsolidation && prefs.includes('parsed.intelligenceCollapsed !== false')))
check('Pipeline renderiza shell recolhível', pipeline.includes('pipeline-intelligence-shell'))
check('toggle usa aria-expanded', pipeline.includes('aria-expanded={!preferences.intelligenceCollapsed}'))
check('estado é persistido por persistPreferences', pipeline.includes('persistPreferences((current) => ({ ...current, intelligenceCollapsed: !current.intelligenceCollapsed }))'))
check('resumo compacto mantém saúde', pipeline.includes('dealPortfolio.averageHealth'))
check('resumo compacto mantém risco', pipeline.includes('dealPortfolio.atRiskValue'))
check('resumo compacto mantém forecast', pipeline.includes('dealPortfolio.predictedValue'))
check('resumo compacto mantém prioridades', pipeline.includes('dealPortfolio.priorities.length'))
check('painel completo só monta expandido', pipeline.includes('!preferences.intelligenceCollapsed ? <div className="pipeline-intelligence-shell__content"'))
check('CSS do shell presente', dealCss.includes('.pipeline-intelligence-shell__header'))
check('CSS responsivo do shell presente', dealCss.includes('@media(max-width:720px){.pipeline-intelligence-shell__header'))
check('Settings possui busca', settings.includes('settingsQuery') && settings.includes('className="settings-search"'))
check('Settings busca por palavras-chave', settings.includes('keywords:') && settings.includes('normalizedQuery'))
check('Settings grupos históricos ou Settings Experience 2.0', settings.includes("['Pessoal', 'Workspace', 'Sistema']") || settings.includes("['Minha experiência', 'Workspace', 'Vendas', 'Conexões', 'Inteligência', 'Administração']"))
check('Settings mostra descrições por seção', settings.includes('description:') && settings.includes('settings-section-intro'))
check('Settings limpa busca ao navegar', settings.includes("setSettingsQuery('')"))
check('diagnóstico recolhível ou saúde sob demanda', settings.includes('diagnosticsCollapsed') && (settings.includes('settings-diagnostics-toggle') || settings.includes('settings-health-chip')))
check('diagnóstico usa aria-expanded', settings.includes('aria-expanded={!diagnosticsCollapsed}'))
check('layout reduz terceira coluna quando recolhido', settingsCss.includes('.settings-v16__body--diagnostics-collapsed'))
check('navegação agrupada estilizada', settingsCss.includes('.settings-nav-group'))
check('busca estilizada', settingsCss.includes('.settings-search'))
check('release notes existem', exists('RELEASE_NOTES_V100.68.2.md'))
check('documentação existe', exists('docs/V100.68.2-SETTINGS-PIPELINE-UX.md'))
check('QA report existe', exists('QA_REPORT_V100.68.2.txt'))
check('npm check inclui V100.68.2', String(pkg.scripts['check:legacy']).includes('qa:v100.68.2'))
check('sem migration V100.68.2', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?68[_-]?2/i.test(name)))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.68.2 Settings & Pipeline UX Audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.68.2 Settings & Pipeline UX Audit: ${checks.length}/${checks.length} contratos aprovados.`)
