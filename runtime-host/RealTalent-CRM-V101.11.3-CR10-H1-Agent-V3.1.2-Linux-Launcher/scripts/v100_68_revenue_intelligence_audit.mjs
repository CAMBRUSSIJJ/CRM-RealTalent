import fs from 'node:fs'
import path from 'node:path'
import { auditRuntimeDependencies } from './runtime-dependency-policy.mjs'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const has = (file, needle) => read(file).includes(needle)
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })
const pkg = JSON.parse(read('package.json'))
const service = read('src/services/revenue-intelligence.ts')
const panel = read('src/features/revenue-intelligence/revenue-intelligence-panel.tsx')
const proposals = read('src/features/proposals/proposals-page.tsx')
const assistant = read('src/services/realtalent-assistant.ts')
const dashboard = read('src/features/dashboard/dashboard-page.tsx')
const versionParts = pkg.version.split('.').map(Number)

check('versão V100.68+', versionParts[0] > 100 || (versionParts[0] === 100 && versionParts[1] >= 68))
check('VERSION acompanha pacote', read('VERSION').trim() === `V${pkg.version}`)
check('APP_VERSION acompanha pacote', has('src/lib/app-version.ts', `APP_VERSION = '${pkg.version}'`))
check('health acompanha pacote', has('public/health.json', pkg.version))
check('title acompanha pacote', has('index.html', `V${pkg.version}`))
check('bridge território acompanha pacote', has('src/features/commercial-map/commercial-map-page.tsx', 'version: APP_VERSION'))
check('sem dependência runtime não aprovada', auditRuntimeDependencies(Object.keys(pkg.dependencies ?? {})).ok)
check('sem migration V100.68', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => name.includes('v100_68')))

check('service Revenue Intelligence existe', exists('src/services/revenue-intelligence.ts'))
check('calculateRevenueIntelligence exportado', service.includes('export function calculateRevenueIntelligence'))
check('categoria sugerida exportada', service.includes('export const suggestedRevenueCategory'))
check('usa Deal Intelligence', service.includes('buildDealIntelligence'))
check('preserva categoria manual', service.includes('manualCategory'))
check('calcula probabilidade RealTalent', service.includes('realTalentProbability'))
check('calcula seller weighted', service.includes('sellerWeightedForecast'))
check('calcula Commit RealTalent', service.includes('commitForecast'))
check('calcula Best Case', service.includes('bestCaseForecast'))
check('calcula full pipeline', service.includes('fullPipelineForecast'))
check('calcula gap para meta', service.includes('gapToGoal'))
check('calcula remaining goal', service.includes('remainingGoal'))
check('calcula pipeline coverage', service.includes('pipelineCoverage'))
check('calcula attainment esperado', service.includes('expectedAttainment'))
check('calcula win rate necessário', service.includes('requiredWinRate'))
check('calcula ticket médio', service.includes('averageDealSize'))
check('calcula deals needed', service.includes('dealsNeeded'))
check('calcula confiança do forecast', service.includes('forecastConfidenceScore'))
check('separa bookings fechados', service.includes('closedBookings'))
check('separa receita reconhecida', service.includes('recognizedRevenue'))
check('separa MRR reconhecido', service.includes('recognizedMrr'))
check('detecta negócios sem data', service.includes('undatedDeals'))
check('detecta drift de categoria', service.includes('suggestedCategoryChanges'))
check('forecast por responsável', service.includes('RevenueOwnerForecast'))
check('risco de cobertura baixa', service.includes("'low-coverage'"))
check('risco de commit fraco', service.includes("'weak-commit'"))
check('risco de forecast concentrado', service.includes("'concentration'"))
check('risco de meta', service.includes("'goal-gap'"))
check('quatro cenários executivos', ['commit','realtalent','best_case','pipeline'].every((value) => service.includes(`scenario: '${value}'`)))

check('painel Revenue Intelligence existe', exists('src/features/revenue-intelligence/revenue-intelligence-panel.tsx'))
check('CSS dedicado V100.68', exists('src/styles/revenue-intelligence-v10068.css'))
check('seletor de mês', panel.includes('setMonthOffset'))
check('KPI meta comercial', panel.includes('Meta comercial'))
check('KPI bookings fechados', panel.includes('Bookings fechados'))
check('KPI Forecast RealTalent', panel.includes('Forecast RealTalent'))
check('KPI confiança', panel.includes('Confiança do forecast'))
check('Pipeline Coverage visível', panel.includes('Pipeline Coverage'))
check('Revenue realization visível', panel.includes('Revenue realization'))
check('Forecast risks visível', panel.includes('Forecast risks'))
check('forecast por responsável visível', panel.includes('Forecast por responsável'))
check('Forecast inspection visível', panel.includes('Forecast inspection'))
check('filtro em risco', panel.includes("setDealFilter('risk')"))
check('filtro drift', panel.includes("setDealFilter('drift')"))
check('manual versus sugerido', panel.includes('Manual:'))
check('contribuição esperada por negócio', panel.includes('Contribuição esperada'))
check('abre Proposal 360', panel.includes('onOpenProposal'))

check('Propostas usa painel novo', proposals.includes('<RevenueIntelligencePanel'))
check('deep link forecast', proposals.includes("routeContext.action === 'forecast'"))
check('Assistant usa Revenue Intelligence', assistant.includes('calculateRevenueIntelligence'))
check('Assistant mostra Commit', assistant.includes('Commit RealTalent'))
check('Assistant mostra cobertura', assistant.includes('Cobertura'))
check('Dashboard usa Revenue Intelligence', dashboard.includes('calculateRevenueIntelligence'))
check('Forecast continua navegável em Propostas', proposals.includes("routeContext.action === 'forecast'") && proposals.includes("setTab('forecast')"))
check('teste unitário dedicado', exists('src/services/revenue-intelligence.test.ts'))
check('release notes', exists('RELEASE_NOTES_V100.68.0.md'))
check('documentação dedicada', exists('docs/V100.68.0-REVENUE-INTELLIGENCE.md'))
check('npm check inclui V100.68', String(pkg.scripts['check:legacy']).includes('qa:v100.68.0'))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'OK' : 'FAIL'} ${item.name}`)
if (failed.length) {
  console.error(`\nV100.68 audit falhou: ${failed.length}/${checks.length}`)
  process.exit(1)
}
console.log(`\nV100.68 Revenue Intelligence & Forecast: ${checks.length}/${checks.length} contratos aprovados.`)
