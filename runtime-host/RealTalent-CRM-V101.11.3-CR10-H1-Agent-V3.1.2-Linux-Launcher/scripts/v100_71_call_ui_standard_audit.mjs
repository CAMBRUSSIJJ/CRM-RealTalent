import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const version = read('src/lib/app-version.ts')
const calls = read('src/features/calls/calls-page.tsx')
const prep = read('src/features/calls/call-session-preparation-modal.tsx')
const workspace = read('src/features/calls/call-workspace-modal.tsx')
const intelligence = read('src/features/calls/calls-intelligence-panel.tsx')
const history = read('src/features/calls/call-history-detail-modal.tsx')
const css = read('src/styles/calls-ui-standard-v10071.css')
const map = read('src/features/commercial-map/commercial-map-page.tsx')
const health = JSON.parse(read('public/health.json'))

const versionParts = String(pkg.version).split('.').map(Number)
const isAtLeast100710 = (versionParts[0] ?? 0) > 100 || ((versionParts[0] ?? 0) === 100 && ((versionParts[1] ?? 0) > 71 || ((versionParts[1] ?? 0) === 71 && (versionParts[2] ?? 0) >= 0)))
check('base V100.71.0 preservada', isAtLeast100710 && version.includes(`APP_VERSION = '${pkg.version}'`))
check('backup schema histórico preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('runtime bridge acompanha pacote', map.includes('version: APP_VERSION'))
check('health acompanha pacote', health.version === pkg.version)
check('stylesheet padrão existe', exists('src/styles/calls-ui-standard-v10071.css'))
check('abas principais usam padrão', (calls.includes('call-tabs call-tabs--page') && calls.includes('role="tablist"') && calls.includes('aria-selected={view ===')) || calls.includes('WorkspaceViewStrip'))
check('abas de preparação usam padrão', prep.includes('call-tabs call-tabs--sub') && prep.includes('aria-selected={activeTab ==='))
check('abas do Modo Foco usam padrão', workspace.includes('call-tabs call-tabs--work') && workspace.includes('aria-selected={workTab ==='))
check('abas de apoio usam padrão', workspace.includes('call-tabs call-tabs--guidance') && workspace.includes('aria-selected={guidanceTab === tab}'))
check('histórico usa segmented padrão', (calls.includes('calls-history-periods call-segmented') && calls.includes('call-segmented__button')) || (calls.includes('calls-filter-drawer-v10167') && calls.includes('historyPeriod')))
check('inteligência usa segmented padrão', intelligence.includes('calls-period-picker call-segmented') && intelligence.includes('aria-pressed={period === value}'))
check('atalhos operacionais usam padrão atual', calls.includes('className="call-action-card"') || (calls.includes('WorkspaceViewStrip') && calls.includes("label: 'Retornos'") && calls.includes("label: 'Quentes'")))
check('modo Focus/Power usa choice card', prep.includes('call-choice-card') && prep.includes('aria-pressed={sessionMode ==='))
check('header do Modo Foco usa Button', workspace.includes('call-session-header-actions call-action-group') && !workspace.includes('className="button button--ghost button--sm"'))
check('delete do histórico usa danger padrão', history.includes('<Button variant="danger" size="sm" onClick={onDelete}>'))
check('ícone destrutivo da lista usa padrão', calls.includes('call-icon-button call-icon-button--danger'))
check('focus-visible padronizado', css.includes('.call-tabs .call-tab:focus-visible') && css.includes('var(--call-focus-ring)'))
check('hierarquia de abas definida', css.includes('.call-tabs--page') && css.includes('.call-tabs--sub') && css.includes('.call-tabs--work') && css.includes('.call-tabs--guidance'))
check('segmented definido', css.includes('.call-segmented .call-segmented__button'))
check('mobile preservado', css.includes('@media (max-width: 760px)'))
check('release notes existem', exists('RELEASE_NOTES_V100.71.0.md'))
check('documentação existe', exists('docs/V100.71.0-CALLING-UI-STANDARD.md'))
check('QA report existe', exists('QA_REPORT_V100.71.0.txt'))
check('npm check inclui V100.71.0', String(pkg.scripts['check:legacy']).includes('qa:v100.71.0'))
check('sem migration V100.71', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?71/i.test(name)))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.71 Calling UI Standard Audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.71 Calling UI Standard Audit: ${checks.length}/${checks.length} contratos aprovados.`)
