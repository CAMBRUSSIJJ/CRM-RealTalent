import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const atLeast = (value, target) => { const a=value.split('.').map(Number), b=target.split('.').map(Number); for(let i=0;i<3;i++){ if((a[i]||0)>(b[i]||0)) return true; if((a[i]||0)<(b[i]||0)) return false } return true }
const version = read('src/lib/app-version.ts')
const health = JSON.parse(read('public/health.json'))
const registry = read('src/features/experience/experience-registry.ts')
const drawer = read('src/features/experience/page-customization-drawer.tsx')
const context = read('src/features/experience/experience-context.tsx')
const tests = read('src/features/experience/experience-context.test.ts')
const boundary = read('src/features/experience/page-experience-boundary.tsx')
const dashboard = read('src/features/dashboard/dashboard-page.tsx')
const pipeline = read('src/features/pipeline/pipeline-page.tsx')
const audit = read('src/services/functional-capability-audit.ts')
const css = read('src/styles/experience-system.css')
const map = read('src/features/commercial-map/commercial-map-page.tsx')

check('linha V100.75 preservada', atLeast(pkg.version, '100.75.0') && version.includes(`APP_VERSION = '${pkg.version}'`))
check('VERSION acompanha pacote', read('VERSION').trim() === `V${pkg.version}`)
check('backup schema preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('health acompanha pacote', health.version === pkg.version && Boolean(health.module))
check('bridge do Território acompanha pacote', map.includes('version: APP_VERSION'))
check('Meu Dia mantém fila real', dashboard.includes('buildWorkdayQueue') && dashboard.includes('buildLeadScoreBoard'))
check('Visualização Inteligente preservada no Pipeline', pipeline.includes('DealPortfolioPanel') && !registry.includes("id: 'intelligence'"))
check('Meu Dia bloqueado não personaliza analytics profundos', registry.includes("id: 'day'") && registry.includes("id: 'day-health'") && !registry.includes(".deal-day-summary"))
check('presets Essencial/Equilibrado/Completo', drawer.includes("applyDashboardLayout('essential')") && drawer.includes("applyDashboardLayout('balanced')") && drawer.includes("applyDashboardLayout('complete')"))
check('posição após saúde', drawer.includes("placeIntelligence('after-health')"))
check('posição após execução', drawer.includes("placeIntelligence('after-execution')"))
check('posição após resumo', drawer.includes("placeIntelligence('after-summary')"))
check('inteligência pode ser ocultada', drawer.includes("placeIntelligence('hidden')") && drawer.includes('<EyeOff'))
check('blocos continuam reordenáveis', drawer.includes('const move = (id: string, direction: -1 | 1)') && drawer.includes('<ArrowUp') && drawer.includes('<ArrowDown'))
check('preferências usam atualização funcional', context.includes('setPreferences((current) => normalizeExperiencePreferences(recipe(current), role))'))
check('migração de ordem existe', context.includes('mergeExperienceSectionOrder') && context.includes('previousKnown'))
check('normalização usa migração de ordem', context.includes('sectionOrder: mergeExperienceSectionOrder(requestedOrder, definitionIds)'))
check('teste cobre contrato bloqueado', tests.includes("sectionOrder).toEqual(['day', 'day-health'])") && tests.includes('hiddenSections).toEqual([])') && tests.includes('mergeExperienceSectionOrder'))
check('boundary aplica ordem e visibilidade', boundary.includes("element.hidden = hidden") && boundary.includes("--experience-order"))
check('auditoria marca personalização funcional', audit.includes("id: 'dashboard-customization'") && audit.includes("name: 'Personalizar visualização', status: 'functional'"))
check('contagem funcional preservada ou ampliada', (audit.match(/status: 'functional'/g) ?? []).length >= 16)
check('contagem parcial não regrediu', (audit.match(/status: 'partial'/g) ?? []).length <= 11)
check('CSS dos presets existe', css.includes('.dashboard-layout-presets') && css.includes('.dashboard-intelligence-placement'))
check('CSS responsivo existe', css.includes('@media (max-width: 640px)') && css.includes('.dashboard-intelligence-placement__buttons'))
check('sem nova migration V100.75', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?75/i.test(name)))
check('release notes existem', exists('RELEASE_NOTES_V100.75.0.md'))
check('documentação existe', exists('docs/V100.75.0-MEU-DIA-EXPERIENCE.md'))
check('QA report existe', exists('QA_REPORT_V100.75.0.txt'))
check('npm check inclui V100.75', String(pkg.scripts['check:legacy']).includes('qa:v100.75.0'))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.75.0 Meu Dia 2.0 audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.75.0 Meu Dia 2.0: ${checks.length}/${checks.length} contratos aprovados.`)
