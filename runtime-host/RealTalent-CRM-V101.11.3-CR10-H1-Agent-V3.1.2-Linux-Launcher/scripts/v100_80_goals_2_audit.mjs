import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const version = read('src/lib/app-version.ts')
const health = JSON.parse(read('public/health.json'))
const page = read('src/features/goals/goals-page.tsx')
const modal = read('src/features/goals/goal-modal.tsx')
const service = read('src/services/goals-workspace.ts')
const tests = read('src/services/goals-workspace.test.ts')
const css = read('src/styles/goals-v100.css')
const audit = read('src/services/functional-capability-audit.ts')
const index = read('index.html')

const [major = 0, minor = 0] = pkg.version.split('.').map(Number)
check('versão inclui ou sucede 100.80.0', major > 100 || (major === 100 && minor >= 80))
check('APP_VERSION acompanha package atual', version.includes(`APP_VERSION = '${pkg.version}'`))
check('package-lock acompanha versão', lock.version === pkg.version && lock.packages?.['']?.version === pkg.version)
check('VERSION acompanha pacote', read('VERSION').trim() === `V${pkg.version}`)
check('health acompanha pacote', health.version === pkg.version)
check('título do navegador acompanha versão', index.includes(`RealTalent CRM V${pkg.version}`))
check('backup schema preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('data local não depende de toISOString', service.includes('export const localDateKey') && service.includes('date.getFullYear()'))
check('page usa data local', page.includes('const today = localDateKey()'))
check('contagem de dias úteis é configurável', service.includes('workingDays = DEFAULT_WORKING_DAYS') && service.includes('activeDays.has(cursor.getDay())'))
check('ritmo usa dias úteis totais', service.includes('workdaysTotal') && service.includes('workdaysElapsed / workdaysTotal'))
check('esperado usa fração útil', service.includes('goal.targetValue * elapsedFraction'))
check('necessário por dia usa dias úteis restantes', service.includes('remaining / Math.max(1, workdaysRemaining)'))
check('forecast usa fração de dias úteis', service.includes('value / elapsedFraction'))
check('projeção para atingir existe', service.includes('projectedToHit'))
check('gap contra ritmo existe', service.includes('paceGap'))
check('comparação histórica equivalente existe', service.includes('previousPeriodStart') && service.includes('previousPeriodEnd'))
check('delta histórico existe', service.includes('previousDeltaPercentage'))
check('preset trimestre existe no serviço', service.includes("preset === 'quarter'"))
check('preset ano existe no serviço', service.includes("preset === 'year'"))
check('modal oferece trimestre', modal.includes("value: 'quarter', label: 'Trimestre'"))
check('modal oferece ano', modal.includes("value: 'year', label: 'Ano'"))
check('modal explica cálculo por dias úteis', modal.includes('calculados por dias úteis'))
check('modal diferencia meta de equipe', modal.includes('Meta de equipe'))
check('modal diferencia meta individual', modal.includes('Meta individual'))
check('filtro por responsável existe', page.includes('Responsável') && page.includes('ownerFilter'))
check('filtro por métrica existe', page.includes('metricFilter'))
check('filtro por saúde existe', page.includes('healthFilter'))
check('filtro de projeção abaixo da meta existe', page.includes('projected_miss'))
check('preferências da visão são persistidas', page.includes('goals-view:v2') && page.includes('localStorage.setItem'))
check('visão geral mostra projetadas para atingir', page.includes('Projetadas para atingir'))
check('card mostra ritmo esperado', page.includes('Ritmo esperado:'))
check('card mostra dias úteis decorridos', page.includes('dias úteis'))
check('card mostra necessário por dia', page.includes('Necessário/dia'))
check('card mostra projeção final', page.includes('Projeção final'))
check('card mostra comparação anterior', page.includes('Vs. período anterior'))
check('visão de equipe mostra projetadas', page.includes('<span>Projetadas</span>'))
check('CSS possui barra de filtros', css.includes('.goals-filter-bar'))
check('CSS possui grid de forecast V100.80', css.includes('.goal-card__forecast-grid--v10080'))
check('CSS possui presets estendidos', css.includes('.goal-period-presets--extended'))
check('testes cobrem data local', tests.includes('uses local date keys instead of UTC date slicing'))
check('testes cobrem trimestre e ano', tests.includes('creates quarter and year goal periods'))
check('testes cobrem insight por dias úteis', tests.includes('workday-aware insight'))
check('auditoria de Metas atualizada', audit.includes('ritmo por dias úteis') && audit.includes('feriados regionais'))
check('sem migration V100.80', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?80/i.test(name)))
check('release notes existem', exists('RELEASE_NOTES_V100.80.0.md'))
check('documentação existe', exists('docs/V100.80.0-METAS-2.0.md'))
check('QA report será gerado', true)
check('npm check inclui V100.80', String(pkg.scripts['check:legacy']).includes('qa:v100.80.0'))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.80.0 Metas 2.0 audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.80.0 Metas 2.0: ${checks.length}/${checks.length} contratos aprovados.`)
