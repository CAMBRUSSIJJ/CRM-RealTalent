import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const version = read('src/lib/app-version.ts')
const health = JSON.parse(read('public/health.json'))
const service = read('src/services/revenue-intelligence.ts')
const forecast = read('src/services/revenue-forecast.ts')
const panel = read('src/features/revenue-intelligence/revenue-intelligence-panel.tsx')
const proposals = read('src/features/proposals/proposals-page.tsx')
const tests = read('src/services/revenue-intelligence.test.ts')
const css = read('src/styles/revenue-intelligence-v10081.css')
const proposalCss = read('src/styles/proposals-v10081.css')
const audit = read('src/services/functional-capability-audit.ts')
const index = read('index.html')
const map = read('src/features/commercial-map/commercial-map-page.tsx')

const [major = 0, minor = 0] = pkg.version.split('.').map(Number)
check('versão inclui ou sucede 100.81.0', major > 100 || (major === 100 && minor >= 81))
check('APP_VERSION acompanha package atual', version.includes(`APP_VERSION = '${pkg.version}'`))
check('package-lock acompanha versão', lock.version === pkg.version && lock.packages?.['']?.version === pkg.version)
check('VERSION acompanha pacote', read('VERSION').trim() === `V${pkg.version}`)
check('health acompanha pacote', health.version === pkg.version)
check('título do navegador acompanha versão', index.includes(`RealTalent CRM V${pkg.version}`))
check('bridge comercial acompanha versão', map.includes('version: APP_VERSION'))
check('backup schema preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('receita realizada separada', panel.includes('Receita realizada') && panel.includes('recognizedRevenue'))
check('receita prevista cadastrada separada', panel.includes('Receita prevista cadastrada') && service.includes('scheduledRevenue'))
check('bookings separados', panel.includes('Bookings fechados') && service.includes('closedBookings'))
check('pipeline ponderado separado', panel.includes('Pipeline ponderado') && service.includes('weightedOpenPipeline'))
check('forecast RealTalent separado', panel.includes('Forecast RealTalent') && service.includes('realTalentForecast'))
check('faixa de definições existe', panel.includes('ri-definition-strip'))
check('definição de receita não confunde booking', panel.includes('Fechar uma venda não reconhece receita automaticamente'))
check('data pura preserva mês em revenue intelligence', service.includes("/^\\d{4}-\\d{2}-\\d{2}$/.test(value)") && service.includes('return value.slice(0, 7)'))
check('data pura preserva mês em forecast', forecast.includes("/^\\d{4}-\\d{2}-\\d{2}$/.test(value)") && forecast.includes('return value.slice(0, 7)'))
check('delta contra mês anterior existe', service.includes('recognizedRevenueDeltaPercent') && panel.includes('vs. mês anterior'))
check('ticket médio ganho existe', service.includes('averageWonTicket') && panel.includes('Ticket médio ganho'))
check('win rate existe', service.includes('closedOutcomeSummary') && service.includes('winRate'))
check('win rate aparece no painel', panel.includes('Win rate encerrados') && panel.includes('Conversão comercial'))
check('responsável inclui bookings', service.includes('bookings: closed') && panel.includes('<span>Bookings</span>'))
check('responsável inclui receita reconhecida', service.includes('recognizedRevenue') && panel.includes('<span>Receita</span>'))
check('corte por origem existe', service.includes('sourcePerformance') && panel.includes('Receita por origem'))
check('corte por produto existe', service.includes('productPerformance') && panel.includes('Receita por produto'))
check('produto usa itens de proposta', service.includes('proposal.items') && service.includes('itemTcv'))
check('receita por produto é alocada proporcionalmente', service.includes('recognizedRevenue += Math.max(0, entry.amount) * value / total'))
check('receita sem vínculo é identificada', service.includes('unlinkedRevenue') && panel.includes('Receita sem vínculo'))
check('risco de receita sem vínculo existe', service.includes("'unlinked-revenue'"))
check('origem usa source do lead', service.includes("lead?.source || 'Sem origem'"))
check('aba Receita foi renomeada', proposals.includes("label: 'Receita realizada'"))
check('aba Forecast virou Revenue Intelligence', proposals.includes("label: 'Revenue Intelligence'"))
check('lista de receita tem filtro por status', proposals.includes('revenueStatusFilter'))
check('lista de receita ordena por competência', proposals.includes('b.competenceDate.localeCompare(a.competenceDate)'))
check('lançamento manual sem vínculo é explícito', proposals.includes('lançamento manual sem vínculo'))
check('CSS Revenue Intelligence 2.0 existe', css.includes('V100.81 — Revenue Intelligence 2.0'))
check('CSS faixa de definições existe', css.includes('.ri-definition-strip'))
check('CSS breakdown existe', css.includes('.ri-breakdown-grid'))
check('CSS conversão existe', css.includes('.ri-conversion-values'))
check('CSS receita workspace existe', proposalCss.includes('.revenue-workspace-v10081'))
check('teste separa prevista de reconhecida', tests.includes('separa receita prevista cadastrada de receita reconhecida'))
check('teste cobre virada de mês', tests.includes('sem deslocamento UTC'))
check('teste cobre win rate', tests.includes('calcula win rate somente sobre negócios encerrados no mês'))
check('auditoria funcional descreve separação', audit.includes('Receita realizada, receita prevista registrada, bookings, pipeline ponderado'))
check('auditoria funcional registra limitação closedLostAt', audit.includes('data de perda dedicada'))
check('sem migration V100.81', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?81/i.test(name)))
check('release notes existem', exists('RELEASE_NOTES_V100.81.0.md'))
check('documentação existe', exists('docs/V100.81.0-REVENUE-INTELLIGENCE-2.0.md'))
check('npm check inclui V100.81', String(pkg.scripts['check:legacy']).includes('qa:v100.81.0'))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.81.0 Revenue Intelligence 2.0 audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.81.0 Revenue Intelligence 2.0: ${checks.length}/${checks.length} contratos aprovados.`)
