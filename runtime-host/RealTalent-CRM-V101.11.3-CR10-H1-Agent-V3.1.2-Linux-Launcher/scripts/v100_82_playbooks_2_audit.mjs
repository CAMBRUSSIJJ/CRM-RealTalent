import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const version = read('src/lib/app-version.ts')
const health = JSON.parse(read('public/health.json'))
const index = read('index.html')
const types = read('src/domain/types.ts')
const page = read('src/features/playbooks/playbooks-page.tsx')
const modal = read('src/features/playbooks/playbook-modal.tsx')
const service = read('src/services/playbook-execution.ts')
const tests = read('src/services/playbook-execution.test.ts')
const css = read('src/styles/playbooks-v10082.css')
const defaults = read('src/domain/defaults.ts')
const map = read('src/features/commercial-map/commercial-map-page.tsx')

const versionParts = pkg.version.split('.').map(Number)
const preservesV10082 = versionParts[0] > 100 || (versionParts[0] === 100 && versionParts[1] >= 82)
check('versão mantém V100.82 ou sucessora', preservesV10082 && version.includes(`APP_VERSION = '${pkg.version}'`))
check('package-lock acompanha versão', lock.version === pkg.version && lock.packages?.['']?.version === pkg.version)
check('VERSION acompanha pacote', read('VERSION').trim() === `V${pkg.version}`)
check('health acompanha pacote', health.version === pkg.version && typeof health.module === 'string' && health.module.length > 0)
check('título do navegador acompanha versão atual', index.includes(`RealTalent CRM V${pkg.version}`))
check('bridge comercial acompanha versão atual', map.includes('version: APP_VERSION'))
check('backup schema preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('tipo de modo de execução existe', types.includes("PlaybookExecutionMode = 'step_by_step' | 'checklist' | 'call' | 'meeting'"))
check('guidance armazena modos', types.includes('executionModes?: PlaybookExecutionMode[]'))
check('guidance armazena segmentos', types.includes('segments?: string[]'))
check('guidance armazena personas', types.includes('personas?: string[]'))
check('guidance armazena discovery', types.includes('discoveryQuestions?: string[]'))
check('guidance armazena objeções', types.includes('objectionPrompts?: string[]'))
check('guidance armazena agenda de reunião', types.includes('meetingAgenda?: string[]'))
check('visão Executar existe', page.includes("'execution'") && page.includes("'library'") && page.includes("'coaching'"))
check('tab Executar existe', page.includes('Executar <span>{activePlaybooks.length}</span>'))
check('modo Passo a passo existe', page.includes("executionMode === 'step_by_step'"))
check('modo Checklist existe', page.includes("executionMode === 'checklist'"))
check('modo Ligação existe', page.includes("executionMode === 'call'"))
check('modo Reunião existe', page.includes("executionMode === 'meeting'"))
check('passo a passo tem navegação', page.includes('Anterior') && page.includes('Próximo'))
check('checklist persiste por workspace/roteiro', page.includes('realtalent.playbook-checklist.v10082') && page.includes('localStorage.setItem'))
check('checklist pode reiniciar', page.includes('Reiniciar') && page.includes('resetChecklist'))
check('ligação separa discovery', page.includes('Perguntas que não podem faltar'))
check('ligação separa objeções', page.includes('Antecipe resistências'))
check('reunião mostra agenda', page.includes('Agenda sugerida'))
check('reunião mostra contexto ideal', page.includes('Contexto ideal'))
check('biblioteca mostra modos', page.includes('playbook-mode-badges'))
check('biblioteca permite executar', page.includes('execute(playbook)') && page.includes('<PlayCircle size={15}/> Executar'))
check('busca inclui segmento e persona', (page.includes('(item.guidance?.segments ?? [])') || page.includes('(guidance.segments ?? [])')) && (page.includes('(item.guidance?.personas ?? [])') || page.includes('(guidance.personas ?? [])')))
check('editor configura os 4 modos', modal.includes("const executionModes: PlaybookExecutionMode[] = ['step_by_step', 'checklist', 'call', 'meeting']"))
check('editor configura segmento', modal.includes('Segmentos · separados por vírgula'))
check('editor configura persona', modal.includes('Personas · separadas por vírgula'))
check('editor configura discovery', modal.includes('Perguntas de discovery · uma por linha'))
check('editor configura objeções', modal.includes('Objeções para preparar · uma por linha'))
check('editor configura agenda', modal.includes('Agenda de reunião · um tópico por linha'))
check('serviço deriva etapas do conteúdo', service.includes(".split(/\\n\\s*\\n/g)"))
check('serviço inclui discovery nas etapas', service.includes("kind: 'discovery' as const"))
check('serviço inclui objeções nas etapas', service.includes("kind: 'objection' as const"))
check('serviço inclui critérios de sucesso', service.includes("kind: 'success' as const"))
check('fallback de execução existe', service.includes('recommendedExecutionMode'))
check('cobertura de execução existe', service.includes('playbookExecutionCoverage'))
check('demo principal usa quatro modos', defaults.includes("executionModes: ['step_by_step', 'checklist', 'call', 'meeting']"))
check('demo principal tem discovery', defaults.includes("discoveryQuestions: ['Como vocês organizam os agendamentos hoje?'"))
check('CSS workspace de execução existe', css.includes('.playbook-execution-shell'))
check('CSS passo a passo existe', css.includes('.playbook-step-workspace'))
check('CSS checklist existe', css.includes('.playbook-checklist-workspace'))
check('CSS ligação/reunião existe', css.includes('.playbook-conversation-grid') && css.includes('.playbook-meeting-grid'))
check('teste de etapas existe', tests.includes('adiciona discovery, objeções e sucesso como etapas'))
check('teste de modo recomendado existe', tests.includes('respeita o primeiro modo configurado'))
check('teste de cobertura existe', tests.includes('mede cobertura de execução e contexto'))
check('sem migration V100.82', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?82/i.test(name)))
check('release notes existem', exists('RELEASE_NOTES_V100.82.0.md'))
check('documentação existe', exists('docs/V100.82.0-ROTEIRO-COMERCIAL-2.0.md'))
check('npm check inclui V100.82', String(pkg.scripts['check:legacy']).includes('qa:v100.82.0'))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.82.0 Roteiro Comercial 2.0 audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.82.0 Roteiro Comercial 2.0: ${checks.length}/${checks.length} contratos aprovados.`)
