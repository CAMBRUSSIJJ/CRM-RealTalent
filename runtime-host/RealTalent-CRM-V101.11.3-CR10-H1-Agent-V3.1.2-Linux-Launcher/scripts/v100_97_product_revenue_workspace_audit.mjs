import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, pass) => checks.push({ label, pass: Boolean(pass) })

const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const health = JSON.parse(read('public/health.json'))
const version = read('src/lib/app-version.ts')
const types = read('src/domain/types.ts')
const defaults = read('src/domain/defaults.ts')
const proposal = read('src/features/proposals/proposals-page.tsx')
const revenue = read('src/features/revenue-intelligence/revenue-intelligence-panel.tsx')
const mapper = read('src/repositories/supabase-repository-mappers.ts')
const localRepo = read('src/repositories/local-crm-repository.ts')
const supabaseRepo = read('src/repositories/supabase-crm-repository.ts')
const productPayloads = read('src/repositories/supabase-product-payloads.ts')
const supabaseTypes = read('src/lib/supabase.types.ts')
const registry = read('src/features/experience/experience-registry.ts')
const settings = read('src/features/settings/page-personalization-settings.tsx')
const css = read('src/styles/product-revenue-v10097.css')
const main = read('src/main.tsx')
const launcher = ((read('start-linux.sh') + '\n' + (fs.existsSync('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (fs.existsSync('scripts/start.mjs') ? read('scripts/start.mjs') : '')) + '\n' + (exists?.('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (exists?.('scripts/start.mjs') ? read('scripts/start.mjs') : ''))
const migration = read('supabase/migrations/202609250001_v100_97_product_revenue_workspace.sql')

check('package preserva V100.97+', (() => { const [major, minor] = pkg.version.split('.').map(Number); return major > 100 || (major === 100 && minor >= 97) })())
check('package-lock acompanha versão', lock.version === pkg.version && lock.packages?.['']?.version === pkg.version)
check('VERSION acompanha package', read('VERSION').trim() === `V${pkg.version}`)
check('APP_VERSION acompanha package', version.includes(`APP_VERSION = '${pkg.version}'`))
check('health acompanha package', health.version === pkg.version)
check('histórico identifica V100.97', read('RELEASE_NOTES_V100.97.0.md').includes('Product & Revenue Workspace'))
check('launcher usa porta dedicada atual', /PORT="\$\{PORT:-\d+\}"/.test(launcher))
check('launcher usa canal da release atual', launcher.includes('VITE_RELEASE_CHANNEL='))
check('launcher valida build antes de abrir', (launcher.includes('npm run build') || launcher.includes('npm run release:verify')) && launcher.includes('dist/index.html'))

check('ProductRecord tem custo unitário', types.includes('unitCost?: number'))
check('ProductRecord tem tipo produto/serviço', types.includes("kind?: 'product' | 'service'"))
check('ProductRecord tem unidade comercial', types.includes('unitLabel?: string'))
check('ProductRecord tem desconto padrão', types.includes('defaultDiscountPercent?: number'))
check('demo traz custos comerciais', defaults.includes('unitCost: 620') && defaults.includes('unitCost: 95'))

check('mapper lê unit_cost', mapper.includes('unitCost: Number(row.unit_cost ?? 0)'))
check('mapper lê product_kind', mapper.includes("kind: row.product_kind ?? 'service'"))
check('mapper lê unidade e desconto padrão', mapper.includes('unitLabel: row.unit_label') && mapper.includes('defaultDiscountPercent'))
check('local repo normaliza custo', localRepo.includes('unitCost: Math.max(0'))
check('local repo limita desconto 0–100', localRepo.includes('Math.min(100'))
check('Supabase create persiste custo', productPayloads.includes('unit_cost: input.unitCost ?? 0'))
check('Supabase create persiste kind/unidade', productPayloads.includes("product_kind: input.kind ?? 'service'") && productPayloads.includes('unit_label: input.unitLabel'))
check('Supabase update persiste campos V100.97', productPayloads.includes('patch.unit_cost') && productPayloads.includes('patch.product_kind') && productPayloads.includes('patch.default_discount_percent') && supabaseRepo.includes('productUpdatePayload(input)'))
check('tipos Supabase incluem unit_cost', supabaseTypes.includes('unit_cost: number'))
check('tipos Supabase incluem product_kind', supabaseTypes.includes("product_kind: 'product' | 'service'"))

check('migration V100.97 existe', exists('supabase/migrations/202609250001_v100_97_product_revenue_workspace.sql'))
check('migration adiciona unit_cost', migration.includes('add column if not exists unit_cost'))
check('migration protege product_kind', migration.includes('products_product_kind_check'))
check('migration protege desconto', migration.includes('products_default_discount_range'))

check('nova linha aplica desconto padrão', proposal.includes('product?.defaultDiscountPercent ?? 0'))
check('modal cadastra custo', proposal.includes('Custo unitário estimado') || proposal.includes('Custo unitário (R$)'))
check('modal cadastra unidade', proposal.includes('Unidade comercial'))
check('modal cadastra tipo', proposal.includes('<span>Tipo</span>'))
check('modal exibe margem de referência', proposal.includes('Margem comercial de referência') || proposal.includes('Margem de referência'))
check('catálogo mostra indicadores', proposal.includes('catalog-insights-v10097') || proposal.includes('catalog-insights-professional'))
check('catálogo mede adoção em propostas', proposal.includes('Adoção nas propostas') || proposal.includes('Uso do catálogo em propostas') || proposal.includes('das propostas usam produto'))
check('catálogo mostra custo e margem', ((proposal.includes('product-card__margin') || proposal.includes('catalog-table')) && (proposal.includes('custo unitário') || proposal.includes('<th>Custo</th>'))) || (proposal.includes('product-studio__content') && proposal.includes('<small>Custo</small>') && proposal.includes('Margem tabela')))
check('catálogo distingue Produto/Serviço', proposal.includes("product.kind === 'product' ? 'Produto' : 'Serviço'"))
check('catálogo esclarece margem comercial', proposal.includes('Margem comercial ≠ margem contábil') || proposal.includes('Margem comercial é uma referência de negociação') || proposal.includes('Margem comercial de referência para negociação') || (proposal.includes('Margem comercial') && proposal.includes('antes de impostos')))

check('Forecast possui presets', revenue.includes('forecastPresets'))
check('Forecast preset Executivo', revenue.includes("applyForecastPreset('executive')"))
check('Forecast preset Vendas', revenue.includes("applyForecastPreset('sales')"))
check('Forecast preset Receita', revenue.includes("applyForecastPreset('revenue')"))
check('Forecast preset Completa', revenue.includes("applyForecastPreset('complete')"))
check('presets preservam seções não-Forecast', revenue.includes('const preserved ='))
check('Forecast orienta refinamento em Configurações', revenue.includes('Configurações → Páginas'))

check('Catálogo entrou no registro de personalização', registry.includes("id: 'catalog-insights'") && registry.includes("id: 'catalog-list'"))
check('Settings nomeia grupo Catálogo', settings.includes("sectionId.startsWith('catalog-') ? 'Catálogo'"))
check('CSS V100.97 importado', main.includes("product-revenue-v10097.css"))
check('CSS possui catálogo responsivo', css.includes('.catalog-insights-v10097') && css.includes('@media (max-width: 760px)'))
check('CSS possui presets do forecast', css.includes('.forecast-presets-v10097'))
check('release notes existem', exists('RELEASE_NOTES_V100.97.0.md'))
check('documentação existe', exists('docs/V100.97.0-PRODUCT-REVENUE-WORKSPACE.md'))
check('script QA registrado', pkg.scripts['qa:v100.97.0'] === 'node scripts/v100_97_product_revenue_workspace_audit.mjs')
check('npm check inclui V100.97', String(pkg.scripts['check:legacy']).includes('qa:v100.97.0'))

for (const item of checks) console.log(`${item.pass ? 'OK' : 'FAIL'}  ${item.label}`)
const failed = checks.filter((item) => !item.pass)
if (failed.length) {
  console.error(`\nV100.97.0 Product & Revenue Workspace falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.97.0 Product & Revenue Workspace: ${checks.length}/${checks.length} contratos aprovados.`)
