import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, pass) => checks.push({ label, pass: Boolean(pass) })
const versionAtLeast = (current, baseline) => { const a = String(current).split('.').map(Number); const b = String(baseline).split('.').map(Number); for (let i = 0; i < Math.max(a.length, b.length); i += 1) { const left = a[i] ?? 0; const right = b[i] ?? 0; if (left > right) return true; if (left < right) return false } return true }

const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const health = JSON.parse(read('public/health.json'))
const runtime = JSON.parse(read('public/runtime-version.json'))
const version = read('src/lib/app-version.ts')
const workspace = read('src/features/calls/call-workspace-modal.tsx')
const prep = read('src/features/calls/call-session-preparation-modal.tsx')
const config = read('src/features/calls/call-session-config.ts')
const voice = read('src/services/voice-dialer.ts')
const voiceSettings = read('src/features/calls/voice-dialer-settings-modal.tsx')
const server = read('scripts/realtalent-connect-server.mjs')
const launcher = ((read('start-linux.sh') + '\n' + (fs.existsSync('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (fs.existsSync('scripts/start.mjs') ? read('scripts/start.mjs') : '')) + '\n' + (exists?.('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (exists?.('scripts/start.mjs') ? read('scripts/start.mjs') : ''))
const configure = read('configure-realtalent-connect.sh')
const css = read('src/styles/calling-workspace.css')

check('package preserva V100.98.2 ou posterior', versionAtLeast(pkg.version, '100.98.2'))
check('package-lock acompanha versão', lock.version === pkg.version && lock.packages?.['']?.version === pkg.version)
check('VERSION acompanha package', read('VERSION').trim() === `V${pkg.version}`)
check('APP_VERSION acompanha package atual', version.includes(`APP_VERSION = '${pkg.version}'`))
check('health acompanha release atual', health.version === pkg.version && health.application === 'RealTalent CRM')
check('runtime acompanha release e preserva porta válida', runtime.version === pkg.version && Number(runtime.default_port) >= 4183)
check('runtime declara Connect 3001', runtime.connect_port === 3001)
check('index permanece RealTalent CRM versionado', read('index.html').includes('RealTalent CRM V'))

check('servidor RealTalent Connect existe', exists('scripts/realtalent-connect-server.mjs'))
check('configurador RealTalent Connect existe', exists('configure-realtalent-connect.sh'))
check('Connect restringe acesso local/LAN com segurança', server.includes("REALTALENT_CONNECT_HOST || '127.0.0.1'") || (server.includes("REALTALENT_CONNECT_HOST || '0.0.0.0'") && server.includes('isOriginAllowed')))
check('Connect expõe health', server.includes('/api/voice/v1/health'))
check('Connect expõe capabilities', server.includes('/api/voice/v1/capabilities'))
check('Connect cria chamadas', server.includes("req.method === 'POST' && url.pathname === '/api/voice/v1/calls'"))
check('Connect consulta estado da chamada', server.includes("req.method === 'GET' && callMatch"))
check('Connect aceita comando hangup', server.includes("command !== 'hangup'"))
check('Connect usa Twilio Agent Bridge', server.includes('Twilio Agent Bridge') || server.includes('twilio_bridge'))
check('Connect lê Account SID', server.includes('TWILIO_ACCOUNT_SID'))
check('Connect lê Auth Token', server.includes('TWILIO_AUTH_TOKEN'))
check('Connect lê número de origem', server.includes('TWILIO_FROM_NUMBER'))
check('Connect lê número do agente', server.includes('REALTALENT_AGENT_PHONE_NUMBER'))
check('credenciais não são devolvidas na API', !server.includes("authToken: twilio.authToken"))
check('bridge chama agente primeiro', server.includes('To: twilio.agentNumber'))
check('bridge conecta o telefone do lead', server.includes('<Number>${xmlEscape(leadPhone)}</Number>'))
check('bridge usa TwiML inline', server.includes('Twiml: dialTwiml'))
check('status Twilio mapeado para VoiceCallState', server.includes('mapTwilioState'))
check('CORS local disponível', server.includes('Access-Control-Allow-Origin'))
check('Connect restringe origem do navegador', server.includes('allowedOrigins') && server.includes('Origem não autorizada'))
check('Connect não usa CORS wildcard', !server.includes("Access-Control-Allow-Origin', '*'"))
check('POST exige JSON', server.includes('Use Content-Type application/json.'))
check('telefone é normalizado para E.164', server.includes('normalizeE164') && server.includes('REALTALENT_DEFAULT_COUNTRY_CODE'))
check('polling distingue perna do agente e do lead', server.includes('ParentCallSid=') && server.includes('childState'))

check('Voice Layer distingue Connect configurado', voice.includes("configured ? 'available' : 'not_configured'"))
check('Voice Layer usa detalhe retornado pelo Connect', voice.includes('payload.detail'))
check('Voice Layer inicia polling de chamada', voice.includes('beginConnectCallPolling'))
check('polling consulta call status', voice.includes('/api/voice/v1/calls/${encodeURIComponent(callId)}'))
check('polling publica voice-event', voice.includes("new CustomEvent('realtalent:voice-event'"))
check('polling encerra em ended/failed', voice.includes("data.state === 'ended' || data.state === 'failed'"))
check('chamada Connect usa contrato v1', voice.includes('REALTALENT_VOICE_CALL_SCHEMA'))
check('hangup remoto preservado', voice.includes('/commands'))

check('preparação possui Playbook/Roteiro da sessão', prep.includes('Playbook da sessão') || prep.includes('Roteiro da sessão'))
check('preparação resolve playbook automático', prep.includes('effectiveSessionPlaybookId'))
check('preparação passa playbook resolvido', prep.includes('playbookId: effectiveSessionPlaybookId'))
check('preparação mantém objetivo', prep.includes('sessionObjective'))
check('preparação mantém fila', prep.includes('orderedSessionLeads'))
check('preparação mantém telefonia antes da sessão', prep.includes('Configurar RealTalent Voice'))
check('preparação explica tela limpa', prep.includes('Durante a ligação, a tela mostra somente o que ajuda a conversa.') || prep.includes('Modo Foco mostra somente o que ajuda a avançar.'))
check('config mantém playbookId', config.includes('playbookId: string'))

check('Modo Foco tem título simplificado', workspace.includes('Modo Foco — Ligações'))
check('Modo Foco exibe playbook/roteiro no cabeçalho', workspace.includes('Playbook: ${sessionPlaybookLabel}') || workspace.includes('Roteiro: ${sessionPlaybookLabel}'))
check('pré-call é etapa separada', workspace.includes('Antes de ligar'))
check('estado dialing orienta agente', workspace.includes('Atenda seu telefone para conectar o lead'))
check('conversa prioriza roteiro', workspace.includes('calling-v982__script-card'))
check('fala sugerida é central', workspace.includes('Fala sugerida'))
check('pergunta do playbook é central', workspace.includes('Pergunta'))
check('coaching é curto', workspace.includes('calling-v982__coaching'))
check('Assistant mostra um sinal útil', workspace.includes('Somente o próximo sinal útil'))
check('objeções ficam recolhíveis', workspace.includes('<summary>Objeções rápidas</summary>'))
check('contexto fica recolhível', workspace.includes('<summary>Mais contexto e anotações</summary>') || workspace.includes('<summary>Contexto, histórico e anotações</summary>'))
check('wrap-up é etapa separada', workspace.includes('Depois da ligação'))
check('wrap-up preserva resultado', workspace.includes('calling-v982__outcomes'))
check('wrap-up preserva próxima ação', workspace.includes('Agendar próxima ação'))
check('salvar continua exigindo tentativa iniciada', workspace.includes("if (!startedAt || session === 'idle')"))
check('hangup Connect antes do wrap', workspace.includes("sendVoiceCommand(voiceSettings, voiceCall, 'hangup')"))
check('registro continua persistindo resultado', workspace.includes('registerCallOutcome'))

check('CSS Calling 3.0 existe', exists('src/styles/calling-workspace.css'))
check('CSS é importado no workspace', workspace.includes("calling-workspace.css"))
check('layout conversa possui 2 áreas controladas', css.includes('calling-v982__conversation') && css.includes('grid-template-columns:minmax(0,1fr) 320px'))
check('layout possui responsividade', css.includes('@media(max-width:1100px)'))
check('script recebe destaque visual', css.includes('calling-v982__say'))
check('wrap-up possui layout dedicado', css.includes('calling-v982__wrap-layout'))

check('launcher usa a porta declarada no runtime', launcher.includes('PORT="${PORT:-' + runtime.default_port + '}"'))
check('launcher inicia Connect', launcher.includes('realtalent-connect-server.mjs'))
check('launcher valida health do Connect', launcher.includes('/api/voice/v1/health'))
check('launcher encerra Connect junto com CRM', launcher.includes('trap cleanup'))
check('launcher mantém preflight', launcher.includes('linux-release-preflight.mjs'))
check('launcher mantém build real', launcher.includes('npm run build') || launcher.includes('npm run release:verify'))
check('launcher valida release atual antes de abrir', launcher.includes('dist/index.html') && (launcher.includes('npm run build') || launcher.includes('npm run release:verify')))
check('configurador protege env local', configure.includes('chmod 600'))
check('configurador orienta agent bridge', configure.includes('toca seu telefone'))
check('configurador evita token em argv', configure.includes('RT_TOKEN="$TOKEN"') && !configure.includes('python3 - "$ENV_FILE" "$SID" "$TOKEN"'))
check('configurador valida E.164', configure.includes('formato E.164'))

check('release notes existem', exists('RELEASE_NOTES_V100.98.2.md'))
check('documentação existe', exists('docs/V100.98.2-REALTALENT-CALLING-3.md'))
check('script QA registrado', pkg.scripts['qa:v100.98.2'] === 'node scripts/v100_98_2_realtalent_calling_3_audit.mjs')
check('npm check inclui V100.98.2', String(pkg.scripts['check:legacy']).includes('qa:v100.98.2'))

for (const item of checks) console.log(`${item.pass ? 'OK' : 'FAIL'}  ${item.label}`)
const failed = checks.filter((item) => !item.pass)
if (failed.length) {
  console.error(`\nV100.98.2 RealTalent Calling 3.0 falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.98.2 RealTalent Calling 3.0: ${checks.length}/${checks.length} contratos aprovados.`)
