import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, pass) => checks.push({ label, pass: Boolean(pass) })

const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const health = JSON.parse(read('public/health.json'))
const runtime = JSON.parse(read('public/runtime-version.json'))
const version = read('src/lib/app-version.ts')
const page = read('src/features/prospecting/prospecting-page.tsx')
const workspace = read('src/services/prospecting-workspace.ts')
const provider = read('src/services/prospecting-provider-gateway.ts')
const dataLayer = read('src/services/prospecting-data-layer.ts')
const vite = read('vite.config.ts')
const edge = read('supabase/functions/prospecting-search/index.ts')
const config = read('supabase/config.toml')
const migration = read('supabase/migrations/202607190003_v100_15_prospecting.sql')
const help = read('src/services/help-center.ts')
const capability = read('src/services/functional-capability-audit.ts')
const css = read('src/styles/prospecting-engine.css')
const main = read('src/main.tsx')
const launcher = ((read('start-linux.sh') + '\n' + (fs.existsSync('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (fs.existsSync('scripts/start.mjs') ? read('scripts/start.mjs') : '')) + '\n' + (exists?.('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (exists?.('scripts/start.mjs') ? read('scripts/start.mjs') : ''))
const keyHelper = read(exists('configure-google-maps.sh') ? 'configure-google-maps.sh' : 'configure-google-places.sh')

const [major, minor] = pkg.version.split('.').map(Number)
const isV10098OrNewer = major > 100 || (major === 100 && minor >= 98)
check('package V100.98.0 ou sucessora', isV10098OrNewer)
check('package-lock acompanha versão', lock.version === pkg.version && lock.packages?.['']?.version === pkg.version)
check('VERSION acompanha package', read('VERSION').trim() === `V${pkg.version}`)
check('APP_VERSION acompanha package', version.includes(`APP_VERSION = '${pkg.version}'`))
check('health acompanha package e preserva release identificável', health.version === pkg.version && Boolean(health.release))
check('runtime acompanha release sucessora', runtime.version === pkg.version && Number(runtime.default_port) >= 4181)
check('index acompanha package', read('index.html').includes(`V${pkg.version}`))

check('launcher preserva isolamento de porta', launcher.includes('PORT="${PORT:-') && launcher.includes('--strictPort'))
check('launcher preserva .env.local existente', launcher.includes('if [ ! -f .env.local ]'))
check('launcher não exige Google para iniciar', launcher.includes('modo assistido') || launcher.includes('OpenStreetMap ativo sem chave'))
check('launcher faz preflight e build real', launcher.includes('linux-release-preflight.mjs') && (launcher.includes('npm run build') || launcher.includes('npm run release:verify')))
check('Prospecting Engine local preservado na Vite runtime', vite.includes('prospectingLocalApi(runtimeEnv)') && (launcher.includes('npm run build') || launcher.includes('npm run release:verify')))
check('helper Google existe', (exists('configure-google-maps.sh') || exists('configure-google-places.sh')) && keyHelper.includes('GOOGLE_MAPS_SERVER_KEY'))
check('helper não imprime a chave', keyHelper.includes('read -rsp'))

check('gateway frontend existe', exists('src/services/prospecting-provider-gateway.ts'))
check('gateway tem diagnostics', provider.includes('getProspectingProviderDiagnostics'))
check('gateway tem search', provider.includes('runProspectingProviderSearch'))
check('gateway diferencia Maps/CNPJ', provider.includes("source === 'maps' || source === 'cnpj'"))
check('gateway suporta Supabase Edge Function', provider.includes("functions.invoke('prospecting-search'"))
check('gateway suporta Linux local', provider.includes("fetch('/api/prospecting/search'"))
check('gateway preserva código de erro do provider', provider.includes("typeof input.code === 'string'") && provider.includes('new ProspectingProviderError(message, code'))
check('gateway não contém segredo literal', !/AIza[0-9A-Za-z_-]{20,}/.test(provider))

check('Vite possui gateway local', vite.includes("name: 'realtalent-prospecting-local-api'"))
check('Vite carrega env server-side', vite.includes("loadEnv(mode, process.cwd(), '')"))
check('Vite usa Places API New', vite.includes('https://places.googleapis.com/v1/places:searchText'))
check('Vite usa field mask explícita', vite.includes('x-goog-fieldmask'))
check('Vite limita Google a 20 resultados', vite.includes('Math.min(20, quantity)'))
check('Vite exige CNPJ com 14 dígitos', vite.includes('cnpj.length !== 14'))
check('Vite usa consulta CNPJ individual', vite.includes("`${base.replace(/\\\/$/, '')}/${cnpj}`"))
check('Vite não implementa loop de CNPJ', !vite.includes('for (let cnpj') && !vite.includes('while (cnpj'))

check('Edge Function existe', exists('supabase/functions/prospecting-search/index.ts'))
check('Edge Function exige usuário', edge.includes('client.auth.getUser()'))
check('Edge Function exige escrita no workspace', edge.includes("rpc('can_write_organization'"))
check('Edge Function usa Google Places New', edge.includes('https://places.googleapis.com/v1/places:searchText'))
check('Edge Function lê secret Google', edge.includes("Deno.env.get('GOOGLE_MAPS_SERVER_KEY')"))
check('Edge Function registra batch', edge.includes("from('prospecting_batches').insert"))
check('Edge Function registra evento', edge.includes("from('prospecting_events').insert"))
check('Edge Function limita Maps a 20', edge.includes('Math.min(20, quantity)'))
check('Edge Function CNPJ é individual', edge.includes('cnpj.length !== 14') && !edge.includes('for (let cnpj'))
check('Supabase config registra função protegida', config.includes('[functions.prospecting-search]') && config.includes('verify_jwt = true'))

check('schema histórico já possui batches', migration.includes('create table if not exists public.prospecting_batches'))
check('schema batch possui metadata', migration.includes("metadata jsonb not null default '{}'::jsonb"))
check('Data Layer segue no fluxo', dataLayer.includes('prospectDataQuality') && dataLayer.includes('prospectIdentityKey'))
check('workspace ainda deduplica', workspace.includes('detectProspectDuplicate') && workspace.includes('parseProspectFile'))

check('página mantém entrada de busca comercial', page.includes('Busca comercial') || page.includes('Garimpo automático') || page.includes('Prospecting Engine V100.98') || page.includes('Prospecção territorial') || page.includes('Buscar empresas'))
check('página exibe Motor de fontes', page.includes('Motor de fontes') || page.includes('Fontes opcionais') || page.includes('Motor local'))
check('página mostra provider Direto/Assistido', page.includes("'Direto' : 'Assistido'"))
check('página usa provider direto / automação quando disponível', page.includes('runProspectingProviderSearch') && (page.includes('runProspectingSearchAutomation') || page.includes('Buscar, importar e analisar')))
check('página faz fallback assistido', page.includes("if (providerError?.code === 'maps_api_key_missing') openSearch()"))
check('resultado direto entra autoanalisado', page.includes("result.drafts.length, true") || page.includes("result.drafts, 'maps', 'import'"))
check('captura manual entra autoanalisada', page.includes("Math.max(1, quantity), true"))
check('RT Capture permanece visível', page.includes('RT Capture'))
check('Instagram é descrito como assistido', page.includes('A descoberta permanece assistida'))
check('CNPJ esclarece consulta individual', page.includes('A consulta cadastral é individual'))

check('CSS V100.98 existe', exists('src/styles/prospecting-engine.css') && css.includes('.prospecting-provider-health-v10098'))
check('CSS V100.98 importado', main.includes("prospecting-engine.css") && !main.includes("prospecting-engine-v10098.css"))
check('Ajuda explica Google/CNPJ/RT Capture', help.includes('Google Places') && (help.includes('RT Capture') || help.includes('RT_Capture')) && (help.includes('consulta cadastral individual') || help.includes('consulta CNPJ é individual')))
check('Auditoria funcional referencia provider gateway', capability.includes('services/prospecting-provider-gateway.ts') && capability.includes('supabase/functions/prospecting-search/index.ts'))
check('release notes existem', exists('RELEASE_NOTES_V100.98.0.md'))
check('documentação existe', exists('docs/V100.98.0-PROSPECTING-ENGINE.md'))
check('script QA registrado', pkg.scripts['qa:v100.98.0'] === 'node scripts/v100_98_prospecting_engine_audit.mjs')
check('npm check inclui V100.98', String(pkg.scripts['check:legacy']).includes('qa:v100.98.0'))

for (const item of checks) console.log(`${item.pass ? 'OK' : 'FAIL'}  ${item.label}`)
const failed = checks.filter((item) => !item.pass)
if (failed.length) {
  console.error(`\nV100.98.0 Prospecting Engine falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.98.0 Prospecting Engine: ${checks.length}/${checks.length} contratos aprovados.`)
