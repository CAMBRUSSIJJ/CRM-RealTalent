import fs from 'node:fs'
import path from 'node:path'

const root=process.cwd()
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const exists=p=>fs.existsSync(path.join(root,p))
const json=p=>JSON.parse(read(p))
const checks=[]
const ok=(label,value)=>checks.push({label,ok:Boolean(value)})

const pkg=json('package.json')
const manifest=json('release-manifest.json')
const css=read('src/styles/login-experience.css')
const authPage=read('src/features/auth/auth-page.tsx')
const splash=read('src/features/auth/brand-splash.tsx')
const auth=read('src/features/auth/auth-context.tsx')
const app=read('src/app/app.tsx')
const sidebar=read('src/components/layout/sidebar.tsx')
const start=read('scripts/start.mjs')
const index=read('index.html')
const changelog=read('CHANGELOG.md')

ok('package preserves V101.11.1 semver for H5',['101.11.1','101.11.2','101.11.3'].includes(pkg.version))
ok('manifest identifies H5 full canvas orbit field',((manifest.release?.hotfix==='H5'&&manifest.release?.hotfixName==='Full Canvas & Orbit Field'&&manifest.release?.hotfixBaseRelease==='V101.11.1-H4')||(manifest.release?.version==='101.11.2'&&manifest.release?.baseRelease==='V101.11.1-H5')||(manifest.release?.version==='101.11.3'&&manifest.release?.baseRelease==='V101.11.2')))
ok('H5 introduces no database migration',manifest.migrations?.expectedCount>=49&&json('supabase/migrations.lock.json').migrations.length>=49)
ok('H5 CSS marker is present',css.startsWith('/* V101.11.1-H5 — Full Canvas & Orbit Field'))
ok('auth canvas uses dynamic viewport height',css.includes('min-height: 100dvh'))
ok('auth background explicitly covers canvas',css.includes('background-size: cover')&&css.includes('background-repeat: no-repeat'))
ok('legacy showcase pseudo circles are disabled',css.includes('.auth-showcase::before')&&css.includes('content: none !important'))
ok('showcase no longer clips page ambience',/\.auth-showcase\s*\{[^}]*overflow:\s*visible/s.test(css))
ok('page orbit field exists',css.includes('.rt-page-orbit-field')&&css.includes('.rt-page-orbit {'))
ok('page orbit field is non-interactive',/\.rt-page-orbit-field\s*\{[^}]*pointer-events:\s*none/s.test(css))
ok('frame orbit spans almost entire viewport',css.includes('.rt-page-orbit--frame')&&css.includes('calc(100% - clamp(48px, 5vw, 92px))'))
ok('wide orbit crosses the full page',css.includes('.rt-page-orbit--wide')&&css.includes('width: 126vw'))
ok('corner orbit extends beyond page edge',css.includes('.rt-page-orbit--corner')&&css.includes('left: 91%'))
ok('orbits have branded orbital points',css.includes('.rt-page-orbit::after')&&css.includes('#79c6dd')&&css.includes('#1d9e75'))
ok('page orbit motion is slow and transform-only',css.includes('68s linear infinite')&&css.includes('58s linear infinite reverse')&&css.includes('46s linear infinite'))
ok('reduced motion includes page orbits',css.includes('.rt-page-orbit,')&&css.includes('animation: none !important'))
ok('auth page renders three page-level orbits',authPage.includes('rt-page-orbit--frame')&&authPage.includes('rt-page-orbit--wide')&&authPage.includes('rt-page-orbit--corner'))
ok('splash renders the same orbit field',splash.includes('rt-page-orbit--frame')&&splash.includes('rt-page-orbit--wide')&&splash.includes('rt-page-orbit--corner'))
ok('H4 transparent logo remains used',exists('public/realtalent-logo-transparent.png')&&read('src/components/ui/realtalent-brand-mark.tsx').includes('/realtalent-logo-transparent.png'))
ok('H1 local login gate remains preserved',authPage.includes('Abrir workspace local')&&authPage.includes('await auth.enterLocal()'))
ok('local UI session remains sessionStorage-backed',auth.includes('window.sessionStorage.getItem')&&auth.includes('window.sessionStorage.setItem'))
ok('logout remains visible and non-destructive',sidebar.includes('Sair da conta')&&sidebar.includes('onClick={() => void signOut()}'))
ok('workspace remains gated behind user',app.includes('if (!user || recoveryMode) return <AuthPage />'))
ok('Supabase password authentication remains intact',auth.includes('client.auth.signInWithPassword'))
ok('runtime requires H5 marker',start.includes("includes('V101.11.1-H5 — Full Canvas & Orbit Field')"))
ok('runtime migrates state from H4 first',start.indexOf('RealTalent-CRM-V101.11.1-H4-Transparent-Logo-Optimized-Motion-Linux-Launcher')>=0&&start.indexOf('RealTalent-CRM-V101.11.1-H4-Transparent-Logo-Optimized-Motion-Linux-Launcher')<start.indexOf('RealTalent-CRM-V101.11.1-H3-Official-Logo-Motion-Linux-Launcher'))
ok('launcher runs H5 QA gate',start.includes("npm(['run', 'qa:v101.11.1:h5'])"))
ok('runtime URL identifies H5 or a verified successor',start.includes('rt_release=101.11.1-h5-full-canvas-orbit-field')||(['101.11.2','101.11.3'].includes(pkg.version)&&(start.includes('rt_release=101.11.3-h1-communications-gateway-recovery')||start.includes('rt_release=101.11.3-h2-runtime-service-recovery'))&&start.includes("'V101.11.1-H5 — Full Canvas & Orbit Field'")))
ok('index carries H5 lineage marker',index.includes('V101.11.1-H5 — Full Canvas & Orbit Field'))
ok('changelog documents H5 first',changelog.includes('# V101.11.1-H5 — Full Canvas & Orbit Field'))
ok('H5 QA gate is registered',pkg.scripts?.['qa:v101.11.1:h5']==='node scripts/v101_11_1_h5_full_canvas_orbit_field_audit.mjs')
ok('H5 QA gate is in architecture',pkg.scripts?.['qa:architecture']?.includes('qa:v101.11.1:h5'))
ok('manifest requires H5 QA gate',manifest.qa?.requiredGates?.includes('qa:v101.11.1:h5'))
ok('H5 release notes exist',exists('RELEASE_NOTES_V101.11.1-H5.md'))

for(const item of checks) console.log(`${item.ok?'OK  ':'FAIL'} ${item.label}`)
const failed=checks.filter(item=>!item.ok)
console.log(`\nV101.11.1-H5 Full Canvas & Orbit Field: ${checks.length-failed.length}/${checks.length} contracts.`)
if(failed.length) process.exit(1)
