import fs from 'node:fs'
const read=(p)=>fs.readFileSync(p,'utf8')
const start=read('scripts/start.mjs')
const page=read('src/features/communications/communications-page.tsx')
const manifest=JSON.parse(read('release-manifest.json'))
const pkg=JSON.parse(read('package.json'))
let pass=0, fail=0
const ok=(label,cond)=>{console.log(`${cond?'OK  ':'FAIL'} ${label}`);cond?pass++:fail++}
ok('current H20.7-H2 inbox marker exists',page.includes('whatsapp-inbox-create-actions is-h207h2'))
ok('launcher still knows H19.11 legacy marker',start.includes("'whatsapp-inbox-create-actions is-h1911'"))
ok('launcher knows H20.7-H2 successor marker',start.includes("'whatsapp-inbox-create-actions is-h207h2'"))
ok('launcher accepts either marker',start.includes('inboxActionMarkers.some((marker) => page.includes(marker))'))
ok('old H19.11 marker is no longer mandatory in generic required array',!start.includes("'V101.11.3-H19.8 — WhatsApp Continuous Chat & Settings Control Center',\n    'whatsapp-inbox-create-actions is-h1911',"))
ok('Pure Chat marker remains mandatory',start.includes("'V101.11.3-H19.7 — WhatsApp Pure Chat'"))
ok('Continuous Chat marker remains mandatory',start.includes("'V101.11.3-H19.8 — WhatsApp Continuous Chat & Settings Control Center'"))
ok('WhatsAppChatPanel remains mandatory',start.includes("'WhatsAppChatPanel'"))
ok('channel switch remains mandatory',start.includes("'communication-channel-switch'"))
ok('launcher hotfix URL marker exists',start.includes('rt_launcher_fix=101.11.3-h21-1-h1-communication-lineage-guard'))
ok('manifest registers launcher hotfix',manifest.launcherHotfix?.buildLabel==='V101.11.3-H21.1-H1')
ok('manifest registers hotfix artifacts',manifest.launcherHotfixArtifacts?.linuxLauncher?.includes('H21.1-H1-Communication-Lineage-Guard-Fix'))
ok('package registers H21.1-H1 gate',Boolean(pkg.scripts?.['qa:v101.11.3:h21.1:h1']))
ok('architecture requires H21.1-H1 gate',pkg.scripts?.['qa:architecture']?.includes('qa:v101.11.3:h21.1:h1'))
ok('release verify requires H21.1-H1 gate',pkg.scripts?.['release:verify']?.includes('qa:v101.11.3:h21.1:h1'))
console.log(`\nH21.1-H1 Communication Lineage Guard Fix: ${pass}/${pass+fail}`)
if(fail)process.exit(1)
