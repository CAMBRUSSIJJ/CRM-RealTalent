import fs from 'node:fs'

const read=(file)=>fs.readFileSync(file,'utf8')
const checks=[]
const check=(name,ok)=>checks.push([name,Boolean(ok)])
const has=(text,value)=>text.includes(value)

const panel=read('src/features/teams/team-access-panel.tsx')
const communications=read('src/features/communications/communications-page.tsx')
const whatsapp=read('src/features/communications/whatsapp-chat-panel.tsx')
const email=read('src/features/communications/email-conversation-panel.tsx')
const official=read('src/features/communications/official-conversation-composer.tsx')
const workToolbar=read('src/features/communications/whatsapp-work-toolbar.tsx')
const proposals=read('src/features/proposals/proposals-page.tsx')
const prospecting=read('src/features/prospecting/prospecting-page.tsx')
const prospectingWorkspace=read('src/services/prospecting-workspace.ts')
const goals=read('src/features/goals/goals-page.tsx')
const app=read('src/app/app-context.tsx')
const migration=read('supabase/migrations/202610120002_v101_11_3_h22_2_cross_module_access_control.sql')
const pkg=JSON.parse(read('package.json'))
const runtime=JSON.parse(read('public/runtime-version.json'))
const health=JSON.parse(read('public/health.json'))
const index=read('index.html')
const launcher=read('scripts/start.mjs')

check('Matriz H22.2 trata Comunicações como recurso por registro',has(panel,"'communications'" ) && has(panel,'recordScopedResources'))
check('Matriz H22.2 trata Propostas como recurso por registro',has(panel,"'proposals'"))
check('Matriz H22.2 trata Garimpo como recurso por registro',has(panel,"'prospecting'"))
check('Matriz H22.2 trata Metas como recurso por registro',has(panel,"'goals'"))

check('Comunicações filtram conversas por escopo',has(communications,"canTeamAccessRecord('communications'"))
check('Comunicações distinguem criar',has(communications,"canTeamAccess('create','communications')"))
check('Comunicações distinguem editar',has(communications,"canTeamAccess('edit','communications')"))
check('Novo contato/grupo respeita criar',has(communications,'canCommunicationCreate') && has(communications,'Novo contato') && has(communications,'Novo grupo'))
check('WhatsApp recebe readOnly',has(communications,'readOnly={!canCommunicationEdit') && has(whatsapp,'readOnly?: boolean'))
check('Composer WhatsApp bloqueia envio em readOnly',has(whatsapp,'disabled={readOnly') && has(whatsapp,'readOnly'))
check('E-mail recebe readOnly',has(email,'readOnly?: boolean') && has(communications,'<EmailConversationPanel'))
check('Composer oficial recebe readOnly',has(official,'readOnly?: boolean') && has(communications,'<OfficialConversationComposer'))
check('Toolbar WhatsApp valida registro',has(workToolbar,"canTeamAccessRecord('communications'"))
check('Toolbar WhatsApp separa edit e assign',has(workToolbar,'canEditCommunication') && has(workToolbar,'canAssignCommunication'))
check('Troca de responsável WhatsApp exige assign',has(workToolbar,'disabled={!canAssignCommunication') || has(workToolbar,'canAssignCommunication'))

check('Propostas filtram carteira por escopo',has(proposals,"canTeamAccessRecord('proposals'"))
check('Propostas separam create/edit/delete/export',['canProposalCreate','canProposalEdit','canProposalDelete','canProposalExport'].every((v)=>has(proposals,v)))
check('Nova proposta exige create',has(proposals,'canProposalCreate') && has(proposals,'Nova proposta'))
check('Catálogo respeita create/delete',has(proposals,'canProposalDelete') && has(proposals,'deleteProduct'))
check('Receita é filtrada pelo escopo',has(proposals,"canTeamAccessRecord('proposals'" ) && has(proposals,'revenueEntries'))
check('Buyer Rooms respeitam carteira da proposta',has(proposals,'buyerRooms') && has(proposals,'canTeamAccessRecord'))
check('Lead picker de proposta respeita escopo',has(proposals,"const leads = useMemo(() => snapshot?.leads.filter((lead) => canTeamAccessRecord('proposals', lead.ownerId)"))
check('AppContext protege criação de proposta',has(app,"assertTeamAccess(teamAccess,'create','proposals'"))
check('AppContext protege edição de proposta',has(app,"assertTeamAccess(teamAccess,'edit','proposals'"))
check('AppContext protege delete de proposta',has(app,"assertTeamAccess(teamAccess,'delete','proposals'"))
check('AppContext protege atribuição de proposta',has(app,"assertTeamAccess(teamAccess,'assign','proposals'"))
check('AppContext protege receita',has(app,'createRevenueEntry') && has(app,"'proposals'"))
check('AppContext protege Buyer Rooms',has(app,'createBuyerRoom') && has(app,"'proposals'"))

check('ProspectRecord persiste createdBy',has(prospectingWorkspace,'createdBy: string | null'))
check('Garimpo remoto mapeia created_by',has(prospectingWorkspace,'created_by: item.createdBy') && has(prospectingWorkspace,'row.created_by'))
check('createProspect recebe autor',has(prospectingWorkspace,'createdBy: string | null = null') && has(prospectingWorkspace,'createdBy,'))
check('Garimpo filtra registros por createdBy',has(prospecting,"canTeamAccessRecord('prospecting'" ) && has(prospecting,'prospectInScope'))
check('Garimpo separa create/edit/delete/export/assign',['canProspectingCreate','canProspectingEdit','canProspectingDelete','canProspectingExport','canProspectingAssign'].every((v)=>has(prospecting,v)))
check('Garimpo bloqueia delete sem permissão',has(prospecting,'Seu perfil não permite excluir empresas do Garimpo'))
check('Garimpo bloqueia export sem permissão',has(prospecting,'Seu perfil não permite exportar dados do Garimpo'))
check('Garimpo restringe owner sem assign',has(prospecting,'canProspectingAssign ? workspaceMembers'))
check('Garimpo aplica readOnly nos workspaces operacionais',has(prospecting,'readOnly={!canProspectingEdit}'))

check('Metas filtram own/team/all',has(goals,"canTeamAccessRecord('goals'"))
check('Metas separam create/edit/delete/assign',['canGoalCreate','canGoalEdit','canGoalDelete','canGoalAssign'].every((v)=>has(goals,v)))
check('Nova meta exige create',has(goals,'canGoalCreate') && has(goals,'Nova meta'))
check('Cards de meta recebem edit/delete',has(goals,'canEdit={canGoalEdit') && has(goals,'canDelete={canGoalDelete'))
check('Modal restringe membros sem assign',has(goals,'canGoalAssign ? members'))
check('AppContext protege create goal',has(app,"assertTeamAccess(teamAccess,'create','goals'"))
check('AppContext protege edit goal',has(app,"assertTeamAccess(teamAccess,'edit','goals'"))
check('AppContext protege delete goal',has(app,"assertTeamAccess(teamAccess,'delete','goals'"))
check('AppContext protege assign goal',has(app,"assertTeamAccess(teamAccess,'assign','goals'"))

check('Migration H22.2 cria helper de owner da Comunicação',has(migration,'rt_communication_owner'))
check('Helper de Comunicação exige membership da organização',has(migration,'where public.is_organization_member(p_organization_id)'))
check('Migration H22.2 cria guard transversal',has(migration,'rt_cross_module_guard'))
check('Guard protege Comunicações',has(migration,"v_resource:='communications'"))
check('Guard protege Propostas',has(migration,"v_resource:='proposals'"))
check('Guard protege Garimpo',has(migration,"v_resource:='prospecting'"))
check('Guard protege Metas',has(migration,"v_resource:='goals'"))
check('Envio em conversa aceita edit sem liberar nova conversa',has(migration,"tg_table_name in ('communication_events','communication_outbox')") && has(migration,"rt_access_action_allowed(v_org,'communications','edit')"))
check('Eventos do Garimpo aceitam create ou edit',has(migration,"tg_table_name='prospecting_events'") && has(migration,"rt_access_action_allowed(v_org,'prospecting','edit')"))
check('RLS protege threads de Comunicação',has(migration,'create policy communication_threads_select'))
check('RLS protege propostas',has(migration,'create policy sales_proposals_select'))
check('RLS protege catálogo',has(migration,'create policy products_select'))
check('RLS protege Garimpo',has(migration,'create policy prospecting_leads_select'))
check('Policy permissiva histórica de eventos do Garimpo é removida',has(migration,'drop policy if exists prospecting_events_write on public.prospecting_events'))
check('RLS protege Metas',has(migration,'create policy goals_select'))
check('Trigger cobre funções SECURITY DEFINER',has(migration,"array['communication_threads','communication_events','communication_outbox','sales_proposals'"))
check('Troca owner de proposta exige assign no banco',has(migration,"new.owner_id is distinct from old.owner_id") && has(migration,"'proposals','assign'"))
check('Troca alvo/escopo de meta exige assign no banco',has(migration,'new.user_id is distinct from old.user_id') && has(migration,"'goals','assign'"))
check('Guard não fica executável diretamente por authenticated',has(migration,'revoke all on function public.rt_cross_module_guard() from public,anon,authenticated'))

check('Script QA H22.2 registrado',has(pkg.scripts?.['qa:v101.11.3:h22.2'] ?? '','v101_11_3_h22_2_cross_module_access_control_audit.mjs'))
check('Runtime smoke H22.2 registrado',has(pkg.scripts?.['runtime:team-access-h22.2'] ?? '','v101_11_3_h22_2_cross_module_access_runtime_smoke.mjs'))
check('Index identifica H22.2',has(index,'V101.11.3-H22.2 — Cross-Module Access Control'))
check('Launcher expõe rt_access2 H22.2',has(launcher,'rt_access2=101.11.3-h22-2-cross-module-access-control'))
check('Runtime anuncia H22.2',runtime.crossModuleAccessControl==='v101.11.3-h22.2')
check('Health anuncia H22.2',health.crossModuleAccessControl==='v101.11.3-h22.2')
check('Runtime anuncia escopo de Comunicações',runtime.communicationsRecordScope==='v101.11.3-h22.2')
check('Runtime anuncia escopo de Propostas',runtime.proposalsRecordScope==='v101.11.3-h22.2')
check('Runtime anuncia escopo de Garimpo',runtime.prospectingRecordScope==='v101.11.3-h22.2')
check('Runtime anuncia escopo de Metas',runtime.goalsRecordScope==='v101.11.3-h22.2')

let failed=0
for(const [name,ok] of checks){console.log(`${ok?'OK  ':'FAIL'} ${name}`); if(!ok) failed++}
console.log(`\nH22.2 Cross-Module Access Control: ${checks.length-failed}/${checks.length} PASS`)
if(failed) process.exit(1)
