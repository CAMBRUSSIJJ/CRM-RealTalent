#!/usr/bin/env node
import fs from 'node:fs'
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8')
const exists=p=>fs.existsSync(new URL(`../${p}`,import.meta.url))
const gateway=read('scripts/realtalent-communications-gateway.mjs')
const bus=read('scripts/communications-realtime-bus.mjs')
const client=read('src/services/local-communications-gateway.ts')
const page=read('src/features/communications/communications-page.tsx')
const globalBridge=read('src/platform/events/use-global-realtime-bridge.ts')
const chat=read('src/features/communications/whatsapp-chat-panel.tsx')
const bridge=read('scripts/whatsapp-browser-qr-bridge.mjs')
const start=((read('start-linux.sh') + '\n' + (fs.existsSync('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (fs.existsSync('scripts/start.mjs') ? read('scripts/start.mjs') : '')) + '\n' + (exists?.('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (exists?.('scripts/start.mjs') ? read('scripts/start.mjs') : ''))
const index=read('index.html')
const checks=[]
const ok=(name,value)=>{checks.push([name,Boolean(value)]);console.log(`${value?'OK  ':'FAIL'} ${name}`)}
ok('gateway atual preserva baseline H12',gateway.includes("const VERSION = '101.8.4-h13'")&&start.includes('V101.8.4-H12 — WhatsApp Realtime'))
ok('bus SSE dedicado existe',exists('scripts/communications-realtime-bus.mjs')&&bus.includes('text/event-stream')===false&&bus.includes('communications.changed'))
ok('endpoint SSE existe',gateway.includes("'/api/communications/stream'"))
ok('SSE usa text/event-stream',gateway.includes("'text/event-stream; charset=utf-8'"))
ok('gateway envia heartbeat',gateway.includes('realtimeBus.heartbeat()'))
ok('saveStore publica mudança',gateway.includes("realtimeBus.publishAll('communications.changed'"))
ok('health expõe realtime',gateway.includes("transport:'sse'"))
ok('frontend usa EventSource',client.includes('new EventSource('))
ok('frontend escuta realtime.ready',client.includes("'realtime.ready'"))
ok('frontend escuta communications.changed',client.includes("'communications.changed'"))
ok('Central assina realtime',page.includes('subscribeGatewayCommunicationsRealtime') || (globalBridge.includes('subscribeGatewayCommunicationsRealtime') && page.includes("useDomainProjectionRevision('communications')")))
ok('refresh realtime é silencioso',page.includes('reloadOfficial(true)'))
ok('refresh realtime usa debounce',page.includes('realtimeRefreshTimerRef'))
ok('polling virou fallback de 60s',page.includes('60_000'))
ok('chat mostra estado tempo real',chat.includes('Tempo real ativo')&&chat.includes('Tempo real reconectando'))
ok('live 1:1 usa fast path sem getChat',bridge.includes('Fast path: mensagens 1:1 com @c.us')&&bridge.includes('isDirectPhoneAddress(rawPeerAddress)'))
ok('Sincronizar virou recuperação de histórico',page.includes('Sincronizar histórico')&&page.includes('Mensagens novas chegam em tempo real'))
ok('start identifica H12',start.includes('V101.8.4-H12 — WhatsApp Realtime'))
ok('start migra H11 para H12',start.includes('RealTalent-CRM-V101.8.4-H11-WhatsApp-Sync-Recovery')&&start.includes('Sessão de comunicações encontrada na versão anterior.'))
ok('index identifica H12',index.includes('V101.8.4-H12 — WhatsApp Realtime'))
ok('release notes H12 existem',exists('RELEASE_NOTES_V101.8.4-H12.md'))
const failed=checks.filter(([,v])=>!v)
console.log(`\nV101.8.4-H12 WhatsApp Realtime: ${checks.length-failed.length}/${checks.length} contratos aprovados.`)
if(failed.length)process.exit(1)
