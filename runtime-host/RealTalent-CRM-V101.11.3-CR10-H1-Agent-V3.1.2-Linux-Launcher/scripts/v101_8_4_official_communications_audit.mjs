import fs from 'node:fs'
const checks=[]
const read=(p)=>fs.readFileSync(p,'utf8')
const assert=(name,ok)=>{checks.push([name,Boolean(ok)]);if(!ok)console.error('FAIL',name)}
const page=read('src/features/communications/communications-page.tsx')
const composer=read('src/features/communications/official-conversation-composer.tsx')
const comm=read('src/services/communication-workspace.ts')
const oauth=read('supabase/functions/integration-oauth-callback/index.ts')
const send=read('supabase/functions/official-communication-send/index.ts')
const sync=read('supabase/functions/communication-sync-now/index.ts')
const migration=read('supabase/migrations/202610010002_v101_8_4_official_communications.sql')
const config=read('supabase/config.toml')
assert('composer embutido na central',page.includes('OfficialConversationComposer'))
assert('composer envia email oficial',composer.includes('sendOfficialEmail'))
assert('composer envia whatsapp oficial',composer.includes('sendOfficialWhatsApp'))
assert('composer escolhe conta conectada',composer.includes('connectedAccountLabel'))
assert('sync manual exposto',comm.includes('communication-sync-now')&&page.includes('syncOfficialCommunications'))
assert('sync edge autenticado',config.includes('[functions.communication-sync-now]')&&config.includes('verify_jwt = true'))
assert('envio tenta dispatch imediato',send.includes('communication-dispatch-worker')&&send.includes('COMMUNICATION_WORKER_SECRET'))
assert('oauth descobre WABA',oauth.includes('owned_whatsapp_business_accounts'))
assert('oauth descobre phone_number_id',oauth.includes('/phone_numbers?fields=')&&oauth.includes('phone_number_id'))
assert('oauth assina app no WABA',oauth.includes('/subscribed_apps'))
assert('inbound reconhece ContactRecord',migration.includes('from public.contacts'))
assert('communication_events tem contact_id',migration.includes('communication_events')&&migration.includes('contact_id uuid references public.contacts'))
assert('timeline carrega contact_id',comm.includes("select('id,lead_id,contact_id"))
assert('lead continua resolvido por contato',migration.includes('primary_contact_id=v_contact_id'))
const failed=checks.filter(([,ok])=>!ok)
console.log(`V101.8.4 Official Communications: ${checks.length-failed.length}/${checks.length} contratos aprovados.`)
if(failed.length)process.exit(1)
