import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8')
const exists = (name) => fs.existsSync(path.join(root, name))
const pkg = JSON.parse(read('package.json'))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const objectRegistry = read('src/platform/metadata/object-registry.ts')
const fieldRegistry = read('src/platform/metadata/field-registry.ts')
const relationRegistry = read('src/platform/metadata/relation-registry.ts')
const adapters = read('src/platform/records/core-adapters.ts')
const snapshotAdapter = read('src/platform/records/workspace-snapshot-adapter.ts')
const validator = read('src/platform/validation/metadata-validator.ts')
const inspector = read('src/platform/metadata/metadata-inspector.ts')
const safety = read('src/services/snapshot-safety.ts')
const main = read('src/main.tsx')
const appVersion = read('src/lib/app-version.ts')
const launcher = ((read('start-linux.sh') + '\n' + (fs.existsSync('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (fs.existsSync('scripts/start.mjs') ? read('scripts/start.mjs') : '')) + '\n' + (exists?.('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (exists?.('scripts/start.mjs') ? read('scripts/start.mjs') : ''))
const tests = read('src/platform/metadata/core-metadata-foundation.test.ts')
const releaseNotes = read('RELEASE_NOTES_V101.9.0.md')

check('versão do package mantém ou sucede ciclo 101.9.x', /^101\.(?:9|10|11)\.\d+$/.test(pkg.version))
check('APP_VERSION acompanha release sucessora do ciclo 101.9.x', appVersion.includes(`APP_VERSION = '${pkg.version}'`) && appVersion.includes(`APP_VERSION_LABEL = 'V${pkg.version}'`))
check('ObjectRegistry existe', exists('src/platform/metadata/object-registry.ts') && objectRegistry.includes('class ObjectRegistry'))
check('registra Lead', objectRegistry.includes("key: 'lead'"))
check('registra ContactRecord', objectRegistry.includes("key: 'contact'"))
check('registra CompanyRecord', objectRegistry.includes("key: 'company'"))
check('registra OpportunityRecord', objectRegistry.includes("key: 'opportunity'"))
check('FieldRegistry existe e cobre relações', fieldRegistry.includes('class FieldRegistry') && fieldRegistry.includes("kind: 'relation'") && fieldRegistry.includes("kind: 'relation-list'"))
check('RelationRegistry existe', relationRegistry.includes('class RelationRegistry') && relationRegistry.includes('lead-company') && relationRegistry.includes('opportunity-lead'))
check('adapters existem para quatro modelos', ['leadAdapter','contactAdapter','companyAdapter','opportunityAdapter'].every((name) => adapters.includes(name)))
check('PlatformRecord preserva legacy', adapters.includes('legacy: record') && adapters.includes('toLegacyRecord'))
check('snapshot possui adapter compatível', snapshotAdapter.includes('adaptWorkspaceSnapshotWithMetadata') && (snapshotAdapter.includes('return snapshot') || snapshotAdapter.includes('return canonical.snapshot')))
check('UI existente passa pela metadata', safety.includes('adaptWorkspaceSnapshotWithMetadata(normalized)'))
check('valida IDs', validator.includes('isMetadataSafeId') && validator.includes("code: 'invalid_id'"))
check('valida duplicidade', validator.includes("code: 'duplicate_id'"))
check('valida workspace', validator.includes("code: 'workspace_mismatch'") && validator.includes("code: 'relation_workspace_mismatch'"))
check('valida relações órfãs', validator.includes("code: 'missing_relation'"))
check('inspector interno existe', inspector.includes('__REALTALENT_METADATA__') && inspector.includes('inspectMetadataFoundation'))
check('inspector é instalado no bootstrap', main.includes('installMetadataInspector()'))
check('testes cobrem compatibilidade e relação órfã', tests.includes('mantém o shape legado') && tests.includes('detecta relação órfã'))
check('migrations permanecem sem alteração V101.9.0', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => name.includes('101_9_0')))
check('release notes registradas', releaseNotes.includes('Core Metadata Foundation') && releaseNotes.includes('nenhuma migration SQL nova'))
check('documentação da arquitetura existe', exists('docs/V101.9.0-CORE-METADATA-FOUNDATION.md') && read('docs/V101.9.0-CORE-METADATA-FOUNDATION.md').includes('WorkspaceSnapshot (mesmo shape)'))
check('release não adiciona camada visual V101.9.0', !fs.readdirSync(path.join(root, 'src/styles')).some((name) => /10190/i.test(name)))
check('launcher sucessor preserva H15', launcher.includes('RealTalent CRM V101.9.1 — Universal View Engine') && launcher.includes('RealTalent CRM V101.8.4-H15 — WhatsApp Contact Identity'))

for (const item of checks) console.log(`${item.ok ? 'OK  ' : 'FAIL'} ${item.label}`)
const failed = checks.filter((item) => !item.ok)
console.log(`\nV101.9.0 Core Metadata Foundation: ${checks.length - failed.length}/${checks.length} contratos aprovados.`)
if (failed.length) {
  console.error(`Falharam: ${failed.map((item) => item.label).join(', ')}`)
  process.exit(1)
}
