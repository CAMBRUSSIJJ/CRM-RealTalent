import fs from 'node:fs'
const read=(p)=>fs.readFileSync(p,'utf8')
const css=read('src/styles/ui-polish.css')
const tokens=read('src/platform/design-system/tokens.ts')
const registry=read('src/platform/design-system/registry.ts')
const main=read('src/main.tsx')
const assertions=[];const expect=(label,value)=>assertions.push([label,Boolean(value)])
const requiredTokens=['--rt-color-brand','--rt-color-brand-strong','--rt-color-canvas','--rt-color-surface','--rt-color-text','--rt-color-border','--rt-space-4','--rt-radius-md','--rt-control-md','--rt-focus']
expect('10 tokens CSS essenciais',requiredTokens.every((item)=>css.includes(item)))
expect('paleta RealTalent canônica',tokens.includes('#1D9E75')&&tokens.includes('#04342C')&&tokens.includes('#F1EFE8')&&tokens.includes('#2C2C2A'))
expect('legacy colors derivam de rt-*',css.includes('--accent:var(--rt-color-brand)')&&css.includes('--text:var(--rt-color-text)'))
expect('button possui quatro variantes',css.includes('rt-button--primary')&&css.includes('rt-button--secondary')&&css.includes('rt-button--ghost')&&css.includes('rt-button--danger'))
expect('controls compartilham altura',css.includes('--rt-control-md:40px')&&css.includes('height:var(--rt-control-md)'))
expect('focus é unificado',css.includes('box-shadow:var(--rt-focus)'))
expect('surface/modal/grid unificados',css.includes('.rt-surface,.panel,.toolbar-card,.data-panel')&&css.includes('.rt-dialog,.modal')&&css.includes('.rt-data-grid,.data-table'))
expect('density compact preservada',css.includes('data-density="compact"'))
expect('density comfortable preservada',css.includes('data-density="comfortable"'))
expect('dark theme preservado',css.includes('data-theme="dark"'))
expect('registry possui 11 primitives',(registry.match(/id: '/g)||[]).length>=11)
expect('stylesheet final vem após legado',main.indexOf('ui-polish.css')>main.indexOf('interaction-ui.css')||main.indexOf('ui-polish.css')>main.indexOf('interaction-ui.css'))
for(const [label,ok] of assertions)console.log(`${ok?'OK  ':'FAIL'} ${label}`)
const failed=assertions.filter(([,ok])=>!ok);console.log(`\nDesign System smoke: ${assertions.length-failed.length}/${assertions.length}`);if(failed.length)process.exit(1)
