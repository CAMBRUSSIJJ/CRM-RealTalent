import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })
const includes = (file, needle) => read(file).includes(needle)

const types = read('src/domain/types.ts')
const engine = read('src/services/coaching-engine.ts')
const playbooks = read('src/features/playbooks/playbooks-page.tsx')
const modal = read('src/features/playbooks/playbook-modal.tsx')
const calls = read('src/features/calls/calls-page.tsx')
const callsIntelligence = read('src/features/calls/calls-intelligence-panel.tsx')
const callHistoryDetail = read('src/features/calls/call-history-detail-modal.tsx')
const workspace = read('src/features/calls/call-workspace-modal.tsx')
const migration = read('supabase/migrations/202609150002_v100_65_coaching_playbooks.sql')

const packageJson = JSON.parse(read('package.json'))
const packageVersionParts = packageJson.version.split('.').map(Number)
check('versão inclui ou sucede V100.65.0', packageVersionParts[0] > 100 || (packageVersionParts[0] === 100 && packageVersionParts[1] >= 65))
check('health acompanha pacote', includes('public/health.json', packageJson.version))
check('title acompanha pacote', includes('index.html', `V${packageJson.version}`))
check('kind battlecard', types.includes("'battlecard'"))
check('kind checklist', types.includes("'checklist'"))
check('PlaybookObjective', types.includes('export type PlaybookObjective'))
check('PlaybookGuidance', types.includes('export interface PlaybookGuidance'))
check('guidance objectives', types.includes('objectives?: PlaybookObjective[]'))
check('guidance stages', types.includes('stageIds?: string[]'))
check('guidance roles', types.includes('decisionRoles?: DecisionRole[]'))
check('guidance outcomes', types.includes('outcomes?: CallOutcome[]'))
check('guidance temperatures', types.includes('temperatures?: LeadTemperature[]'))
check('guidance coachingFocus', types.includes('coachingFocus?: string'))
check('guidance successCriteria', types.includes('successCriteria?: string[]'))
check('guidance avoidPhrases', types.includes('avoidPhrases?: string[]'))
check('engine evaluateCallCoaching', engine.includes('export function evaluateCallCoaching'))
check('engine team summary', engine.includes('export function buildTeamCoachingSummary'))
check('engine recommendation', engine.includes('export function recommendPlaybooks'))
check('engine coverage', engine.includes('export function playbookCoverage'))
check('score result dimension', engine.includes("id: 'outcome'"))
check('score discovery dimension', engine.includes("id: 'discovery'"))
check('score next step dimension', engine.includes("id: 'next_step'"))
check('score stakeholder dimension', engine.includes("id: 'stakeholder'"))
check('score objections dimension', engine.includes("id: 'objection'"))
check('score documentation dimension', engine.includes("id: 'documentation'"))
check('score playbook dimension', engine.includes("id: 'playbook'"))
check('coaching strengths', engine.includes('strengths'))
check('coaching improvements', engine.includes('improvements'))
check('objection extraction', engine.includes('extractObjections'))
check('adaptive objective weight', engine.includes("'objetivo da ligação'"))
check('adaptive stage weight', engine.includes("'etapa do pipeline'"))
check('adaptive role weight', engine.includes("'persona/stakeholder'"))
check('adaptive outcome weight', engine.includes("'resultado da conversa'"))
check('adaptive temperature weight', engine.includes("'temperatura do lead'"))
check('Playbooks coaching view', playbooks.includes("view === 'coaching'"))
check('Playbooks contextual rate', playbooks.includes('contextualRate'))
check('Playbooks stage coverage', playbooks.includes('stageCoverage'))
check('Playbooks score dashboard', playbooks.includes('Score médio'))
check('Playbooks objections dashboard', playbooks.includes('O que aparece nas conversas'))
check('Modal objective picker', modal.includes('Objetivo da ligação'))
check('Modal pipeline picker', modal.includes('Etapa do pipeline'))
check('Modal persona picker', modal.includes('Persona / papel na decisão'))
check('Modal outcome picker', modal.includes('Resultado da conversa'))
check('Modal temperature picker', modal.includes('Temperatura'))
check('Modal success criteria', modal.includes('Critérios de sucesso'))
check('Modal avoid phrases', modal.includes('Evitar · um por linha'))
check('Calls coaching view', calls.includes('CallsIntelligencePanel') && callsIntelligence.includes('Qualidade da execução'))
check('Calls coaching score badge', calls.includes('call-coaching-score'))
check('Calls coaching dimensions', callHistoryDetail.includes('call-coaching-dimensions'))
check('Call workspace script recommendations', workspace.includes('scriptRecommendations'))
check('Call workspace battlecard recommendations', workspace.includes('battlecardRecommendations'))
check('Call workspace checklist recommendations', workspace.includes('checklistRecommendations'))
check('Call workspace recommendation reasons', workspace.includes('Por que foi recomendado'))
check('Call workspace coaching focus', workspace.includes('call-playbook-coaching-focus'))
check('Objections contextual ranking', workspace.includes("kind: 'objection'"))
check('Migration guidance jsonb', migration.includes('guidance jsonb'))
check('Migration expanded kind constraint', migration.includes("'battlecard','checklist'"))
check('Migration GIN index', migration.includes('playbooks_guidance_gin_idx'))
check('Supabase mapper guidance', includes('src/repositories/supabase-repository-mappers.ts', 'row.guidance'))
check('Supabase create guidance', includes('src/repositories/supabase-crm-repository.ts', 'guidance: (input.guidance ?? {})'))
check('Update playbook guidance', includes('src/repositories/crm-repository.ts', "'guidance'"))
check('Dedicated CSS', fs.existsSync(path.join(root, 'src/styles/coaching-playbooks-v10065.css')))
check('Engine tests', fs.existsSync(path.join(root, 'src/services/coaching-engine.test.ts')))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'OK' : 'FAIL'} ${item.name}`)
if (failed.length) {
  console.error(`\nV100.65 audit falhou: ${failed.length}/${checks.length}`)
  process.exit(1)
}
console.log(`\nV100.65 Coaching & Playbooks: ${checks.length}/${checks.length} contratos aprovados.`)
