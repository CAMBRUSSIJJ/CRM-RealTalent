import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const version = read('src/lib/app-version.ts')
const calls = read('src/features/calls/calls-page.tsx')
const intelligence = read('src/features/calls/calls-intelligence-panel.tsx')
const history = read('src/features/calls/call-history-detail-modal.tsx')
const service = read('src/services/call-intelligence.ts')
const prep = read('src/features/calls/call-session-preparation-modal.tsx')
const workspace = read('src/features/calls/call-workspace-modal.tsx')
const css = read('src/styles/calls-v10069.css')
const navigation = read('src/components/layout/navigation.ts')

const versionParts = String(pkg.version).split('.').map(Number)
const isAtLeast100690 = versionParts[0] > 100 || (versionParts[0] === 100 && (versionParts[1] > 69 || (versionParts[1] === 69 && versionParts[2] >= 0)))
check('base V100.69.0 preservada', isAtLeast100690 && version.includes(`APP_VERSION = '${pkg.version}'`))
check('backup schema histórico preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('três áreas principais', calls.includes("type CallsView = 'operation' | 'history' | 'intelligence'"))
check('aba Operação', calls.includes('Operação') && calls.includes("view === 'operation'"))
check('aba Histórico', calls.includes('Histórico') && calls.includes("view === 'history'"))
check('aba Inteligência', calls.includes('Inteligência') && calls.includes("view === 'intelligence'"))
check('abas antigas removidas', !calls.includes("view === 'performance'") && !calls.includes("view === 'coaching'"))
check('CTA Começar ligações', calls.includes('Começar ligações'))
check('próximo da fila', calls.includes('Próximo da fila') && (calls.includes('calls-next-call-card') || calls.includes('calls-command-center-v10171__next')))
check('sessões rápidas/evolução por views', (calls.includes('calls-session-presets') && calls.includes('Prioridade de hoje')) || (calls.includes('WorkspaceViewStrip') && calls.includes("label: 'Hoje'") && calls.includes("label: 'Retornos'") && calls.includes("label: 'Quentes'") && calls.includes("label: 'Propostas'")))
check('fila operacional', calls.includes('Fila operacional'))
check('priorização RealTalent', calls.includes('Prioridade RealTalent'))
check('histórico com períodos', calls.includes('historyPeriod') && calls.includes("['today', 'Hoje']") && calls.includes("['30d', '30 dias']"))
check('histórico com busca', calls.includes('Buscar no histórico'))
check('histórico com detalhe', calls.includes('CallHistoryDetailModal') && history.includes('Detalhes da ligação'))
check('detalhe abre Lead', history.includes('Abrir Lead'))
check('detalhe permite nova ligação', history.includes('Nova ligação'))
check('detalhe mostra coaching', history.includes('Qualidade da execução'))
check('detalhe mostra transcrição', history.includes('Transcrição'))
check('inteligência por período', intelligence.includes('calls-period-picker') && intelligence.includes('30 dias'))
check('funil de chamadas', intelligence.includes('Funil de chamadas') && service.includes("label: 'Tentativas'") && service.includes("label: 'Vendas'"))
check('métrica de conexão', service.includes('connectionRate'))
check('métrica de qualificação', service.includes('qualificationRate'))
check('métrica de reunião', service.includes('meetingRate'))
check('horários', intelligence.includes('Quando as pessoas atendem') && service.includes('hourly'))
check('resultados', intelligence.includes('Distribuição das ligações'))
check('coaching unificado', intelligence.includes('Qualidade da execução') && service.includes('buildTeamCoachingSummary'))
check('objeções unificadas', intelligence.includes('Padrões das conversas'))
check('playbooks unificados', intelligence.includes('Cobertura da operação') && service.includes('playbookCoverage'))
check('preparação renomeada', prep.includes('title="Preparar ligações"') && prep.includes('Começar ligações'))
check('playbook automático na preparação', (prep.includes('Automático · melhor playbook para o contexto') || prep.includes('strategy.autoSelectPlaybook')) && prep.includes("setPlaybookId('')"))
check('Modo Foco explícito', workspace.includes('title="Modo Foco — Ligações"'))
check('navegação descreve nova arquitetura', navigation.includes('Operação, histórico e inteligência de chamadas'))
check('CSS responsivo três abas', css.includes('.calls-view-tabs--v69') && css.includes('@media(max-width:700px)'))
check('CSS sessões rápidas', css.includes('.calls-session-presets'))
check('CSS histórico detalhado', css.includes('.call-history-detail'))
check('CSS inteligência', css.includes('.calls-intelligence-workspace'))
check('release notes existem', exists('RELEASE_NOTES_V100.69.0.md'))
check('documentação existe', exists('docs/V100.69.0-CALLING-EXPERIENCE.md'))
check('QA report existe', exists('QA_REPORT_V100.69.0.txt'))
check('npm check inclui V100.69.0', String(pkg.scripts['check:legacy']).includes('qa:v100.69.0'))
check('teste do motor existe', exists('src/services/call-intelligence.test.ts'))
check('sem migration V100.69', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?69/i.test(name)))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.69 Calling Experience Audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.69 Calling Experience Audit: ${checks.length}/${checks.length} contratos aprovados.`)
