import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const version = read('src/lib/app-version.ts')
const prep = read('src/features/calls/call-session-preparation-modal.tsx')
const css = read('src/styles/calls-v10070.css')
const map = read('src/features/commercial-map/commercial-map-page.tsx')
const health = JSON.parse(read('public/health.json'))

const versionParts = String(pkg.version).split('.').map(Number)
const isAtLeast100700 = (versionParts[0] ?? 0) > 100 || ((versionParts[0] ?? 0) === 100 && ((versionParts[1] ?? 0) > 70 || ((versionParts[1] ?? 0) === 70 && (versionParts[2] ?? 0) >= 0)))
check('base V100.70.0 preservada', isAtLeast100700 && version.includes(`APP_VERSION = '${pkg.version}'`))
check('backup schema histórico preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('runtime bridge acompanha pacote', map.includes('version: APP_VERSION'))
check('health acompanha pacote', health.version === pkg.version)
check('preparação preservada/evoluída em quatro passos', (prep.includes("type PreparationTab = 'queue' | 'strategy' | 'settings'") || prep.includes("type PreparationTab = 'queue' | 'settings' | 'strategy' | 'review'")) && prep.includes('Quem ligar') && prep.includes('Roteiro e objetivo') && prep.includes('Como ligar'))
check('fila selecionável', prep.includes('selectedIds') && prep.includes('toggleLead') && prep.includes('Selecionar visíveis'))
check('busca da fila', prep.includes('Buscar lead, empresa, contato ou telefone'))
const sharedPreparationFilterEngine = exists('src/styles/interaction-ui.css') && prep.includes('preparationFilterFields') && prep.includes('WorkspaceFilterMenu')
check('filtro por origem', (prep.includes('>Origem</span>') && prep.includes('sourceFilter')) || (sharedPreparationFilterEngine && prep.includes("{ key: 'source', label: 'Origem'") && prep.includes('sourceFilter')))
check('filtro por segmento', (prep.includes('>Segmento</span>') && prep.includes('segmentFilter')) || (sharedPreparationFilterEngine && prep.includes("{ key: 'segment', label: 'Segmento'") && prep.includes('segmentFilter')))
check('filtro por cidade', (prep.includes('>Cidade</span>') && prep.includes('cityFilter')) || (sharedPreparationFilterEngine && prep.includes("{ key: 'city', label: 'Cidade'") && prep.includes('cityFilter')))
check('filtro por etapa', (prep.includes('>Etapa</span>') && prep.includes('stageFilter')) || (sharedPreparationFilterEngine && prep.includes("{ key: 'stage', label: 'Etapa'") && prep.includes('stageFilter')))
check('filtro por prioridade', prep.includes('priorityFilter'))
check('filtro por temperatura', prep.includes('temperatureFilter'))
check('listas reutilizáveis', prep.includes('SavedCallList') && prep.includes('Salvar seleção atual') && prep.includes('realtalent:call-lists:'))
check('validação sem telefone', prep.includes('missingPhone') && prep.includes('sem telefone'))
check('validação não contatar', prep.includes('blocked') && prep.includes('não contatar'))
check('validação duplicados', prep.includes('duplicates') && (prep.includes('números duplicados') || prep.includes('duplicados')))
check('validação já contatados hoje', prep.includes('contactedToday') && (prep.includes('já contatados hoje') || prep.includes('contatados hoje')))
check('validação reunião futura', prep.includes('meeting') && prep.includes('Reunião agendada'))
check('ordem inteligente', prep.includes("order === 'smart'") && prep.includes('Prioridade inteligente'))
check('objetivo comercial', prep.includes('CALL_SESSION_OBJECTIVES') && prep.includes('Objetivo da sessão'))
check('Focus e Power assistido', prep.includes('Focus') && prep.includes('Power assistido'))
check('playbook automático', prep.includes('Automático · melhor playbook para o contexto') || prep.includes('strategy.autoSelectPlaybook'))
check('meta e máximo da sessão', prep.includes('Máximo da sessão') && (prep.includes('Meta de conversas') || prep.includes('Conversas nesta sessão')))
check('wrap-up inteligente', prep.includes('Wrap-up inteligente'))
check('próximo contato é controlado ou evoluiu para Fast Dial/One-Tap explícito', prep.includes('não disca sozinho') || ((prep.includes('Discagem rápida via Connect') || prep.includes('One-Tap via RealTalent Connect')) && prep.includes('Enviar o próximo contato automaticamente')))
check('resumo da sessão', prep.includes('Resumo da sessão') && prep.includes('estimativa da sessão'))
check('CTA único operacional', prep.includes('Começar ligações'))
check('CSS desktop profissional', css.includes('.call-preparation-v70__layout') && css.includes('grid-template-columns:minmax(0,1fr) 300px'))
check('CSS tablet responsivo', css.includes('@media(max-width:1040px)'))
check('CSS mobile responsivo', css.includes('@media(max-width:760px)') && css.includes('@media(max-width:500px)'))
check('release notes existem', exists('RELEASE_NOTES_V100.70.0.md'))
check('documentação existe', exists('docs/V100.70.0-CALL-PREPARATION-WORKSPACE.md'))
check('QA report existe', exists('QA_REPORT_V100.70.0.txt'))
check('npm check inclui V100.70.0', String(pkg.scripts['check:legacy']).includes('qa:v100.70.0'))
check('sem migration V100.70', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?70/i.test(name)))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.70 Call Preparation Workspace Audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.70 Call Preparation Workspace Audit: ${checks.length}/${checks.length} contratos aprovados.`)
