import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const version = read('src/lib/app-version.ts')
const health = JSON.parse(read('public/health.json'))
const mapPage = read('src/features/commercial-map/commercial-map-page.tsx')
const runtime = read('public/commercial-map-runtime.js')
const mapCss = read('src/styles/commercial-map-v10079.css')
const account = read('src/features/leads/account-360-modal.tsx')
const graph = read('src/features/leads/account-relationship-graph.tsx')
const accountCss = read('src/styles/account-360.css')
const audit = read('src/services/functional-capability-audit.ts')

const versionParts = pkg.version.split('.').map(Number)
const atLeast10079 = versionParts[0] > 100 || (versionParts[0] === 100 && (versionParts[1] > 79 || (versionParts[1] === 79 && versionParts[2] >= 0)))
check('versão >= 100.79.0', atLeast10079 && version.includes(`APP_VERSION = '${pkg.version}'`))
check('package-lock acompanha versão', lock.version === pkg.version && lock.packages?.['']?.version === pkg.version)
check('VERSION acompanha pacote', read('VERSION').trim() === `V${pkg.version}`)
check('backup schema preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('health acompanha pacote', health.version === pkg.version)
check('bridge do mapa acompanha pacote', mapPage.includes('version: APP_VERSION'))
check('CSS específico do mapa é importado', mapPage.includes("commercial-map-v10079.css"))
check('runtime usa mount V100.79', runtime.includes("root.dataset.mounted === '10079'") && runtime.includes("root.dataset.mounted='10079'"))
check('hero padronizado como mapa comercial', runtime.includes('Mapa comercial') && runtime.includes('Território e contas'))
check('diagnóstico possui rótulo explícito', runtime.includes('Diagnóstico do mapa'))
check('processamento de localização possui rótulo explícito', runtime.includes('Processar pendências'))
check('filtro de risco da conta existe', runtime.includes('data-filter="accountRisk"') && runtime.includes('Sem mapa da conta'))
check('filtro de risco é aplicado aos leads', runtime.includes("summary?.risk===state.accountRisk"))
check('resumo territorial inclui cobertura comercial', runtime.includes('Cobertura comercial') && runtime.includes('sem decisor'))
check('preferências do mapa são persistidas por workspace', runtime.includes('realtalent-map-preferences:${db.workspace}') && runtime.includes('saveMapPreferences'))
check('preferências incluem mapa-base', runtime.includes('baseMap:state.baseMap'))
check('preferências incluem visualização', runtime.includes('view:state.view'))
check('preferências incluem coloração', runtime.includes('markerMode:state.markerMode'))
check('preferências incluem prospects', runtime.includes('showProspects:state.showProspects'))
const usesV101MapRuntime = versionParts[0] >= 101
check('mapa claro preservado', usesV101MapRuntime ? runtime.includes("light:{url:'https://tile.openstreetmap.org/{z}/{x}/{y}.png'") : runtime.includes('basemaps.cartocdn.com/light_all'))
check('mapa de ruas usa OpenStreetMap', runtime.includes('tile.openstreetmap.org/{z}/{x}/{y}.png'))
check('mapa escuro preservado', usesV101MapRuntime ? runtime.includes("dark:{url:'https://tile.openstreetmap.org/{z}/{x}/{y}.png'") : runtime.includes('basemaps.cartocdn.com/dark_all'))
check('filtros CSS antigos não distorcem novos tiles', mapCss.includes('filter:none!important'))
check('ficha territorial usa organograma da conta', runtime.includes('Organograma da conta'))
check('ficha territorial abre mapa da conta', runtime.includes('Abrir mapa da conta'))
check('Account 360 usa Organograma de decisão', account.includes('Organograma de decisão'))
check('switch chama visualização de Organograma', account.includes('>Organograma</button>'))
check('grafo possui níveis decisórios', graph.includes('Decisão final') && graph.includes('Patrocínio e aprovação') && graph.includes('Influência e validação') && graph.includes('Operação e uso'))
check('grafo destaca estado de contato', graph.includes('Já contatado') && graph.includes('Ainda não contatado'))
check('CSS do grafo possui faixas de nível', accountCss.includes('.relationship-graph-levels'))
check('cards possuem ação Ligar', account.includes("openContactChannel(contact, 'call')"))
check('cards possuem ação WhatsApp', account.includes("openContactChannel(contact, 'whatsapp')"))
check('cards possuem ação E-mail', account.includes("openContactChannel(contact, 'email')"))
check('ações respeitam doNotContact', account.includes('contact.doNotContact'))
check('oportunidades relacionadas aparecem no Account 360', account.includes('Oportunidades relacionadas'))
check('auditoria promove Mapa/Território para funcional', audit.includes("id: 'territory-map', area: 'Operação', name: 'Mapa / Território', status: 'functional'"))
check('auditoria documenta organograma evoluído', audit.includes('organograma por nível decisório'))
check('sem migration V100.79', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?79/i.test(name)))
check('release notes existem', exists('RELEASE_NOTES_V100.79.0.md'))
check('documentação existe', exists('docs/V100.79.0-MAPA-DE-CONTAS-2.0.md'))
check('npm check inclui V100.79', String(pkg.scripts['check:legacy']).includes('qa:v100.79.0'))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.79.0 Mapa de Contas audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.79.0 Mapa de Contas 2.0: ${checks.length}/${checks.length} contratos aprovados.`)
