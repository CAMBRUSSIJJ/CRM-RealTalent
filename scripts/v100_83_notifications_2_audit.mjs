import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const version = read('src/lib/app-version.ts')
const health = JSON.parse(read('public/health.json'))
const index = read('index.html')
const experience = read('src/features/experience/experience-context.tsx')
const notificationPreferences = read('src/services/notification-preferences.ts')
const engine = read('src/services/notification-engine.ts')
const watcher = read('src/features/experience/browser-notification-watcher.tsx')
const center = read('src/features/experience/notification-center.tsx')
const topbar = read('src/components/layout/topbar.tsx')
const shell = read('src/components/layout/app-shell.tsx')
const settings = read('src/features/settings/settings-page.tsx')
const audit = read('src/services/functional-capability-audit.ts')
const tests = read('src/services/notification-engine.test.ts')
const css = read('src/styles/settings-v100.css') + read('src/styles/experience-system.css')
const map = read('src/features/commercial-map/commercial-map-page.tsx')

const atLeast10083 = Number(pkg.version.split('.').slice(0,2).join('.')) >= 100.83
check('versão V100.83 ou sucessora', atLeast10083 && version.includes(`APP_VERSION = '${pkg.version}'`))
check('package-lock acompanha versão', lock.version === pkg.version && lock.packages?.['']?.version === pkg.version)
check('VERSION acompanha pacote', read('VERSION').trim() === `V${pkg.version}`)
check('health acompanha pacote', health.version === pkg.version && (pkg.version === '100.83.0' ? health.module === 'notifications-2.0' : Boolean(health.module)))
check('título do navegador acompanha versão', index.includes(`RealTalent CRM V${pkg.version}`))
check('bridge comercial acompanha versão', map.includes('version: APP_VERSION'))
check('backup schema preservado', version.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('preferências evoluíram para versão 3 ou sucessora', /version:\s*[3-9]/.test(experience))
check('tipo NotificationPreferences existe', notificationPreferences.includes('export interface NotificationPreferences'))
check('canal interno configurável', notificationPreferences.includes('inAppEnabled: boolean'))
check('canal browser configurável', notificationPreferences.includes('browserEnabled: boolean'))
check('frequência configurável', notificationPreferences.includes("NotificationFrequency = 'realtime' | 'hourly' | 'daily'"))
check('horário silencioso configurável', notificationPreferences.includes('quietHoursEnabled: boolean') && notificationPreferences.includes('quietStart: string') && notificationPreferences.includes('quietEnd: string'))
check('janela de antecedência configurável', notificationPreferences.includes('upcomingWindowHours: number'))
check('silêncio de proposta configurável', notificationPreferences.includes('proposalSilenceDays: number'))
check('evento follow-up atrasado existe', notificationPreferences.includes('overdueActivities: boolean'))
check('evento próxima atividade existe', notificationPreferences.includes('upcomingActivities: boolean'))
check('evento reunião próxima existe', notificationPreferences.includes('upcomingEvents: boolean'))
check('evento proposta sem avanço existe', notificationPreferences.includes('proposalFollowups: boolean'))
check('evento lead parado existe', notificationPreferences.includes('staleLeads: boolean'))
check('evento meta em risco existe', notificationPreferences.includes('goalsAtRisk: boolean'))
check('evento falha de automação existe', notificationPreferences.includes('automationFailures: boolean'))
check('preferências antigas recebem fallback seguro', experience.includes('value.notifications?.upcomingActivities !== false') && experience.includes('value.notifications?.staleLeads !== false'))
check('motor central de notificações existe', exists('src/services/notification-engine.ts') && engine.includes('buildNotificationAlerts'))
check('motor gera follow-up vencido', engine.includes("category: 'overdue_activity'"))
check('motor gera próxima atividade', engine.includes("category: 'upcoming_activity'"))
check('motor gera reunião próxima', engine.includes("category: 'upcoming_event'"))
check('motor detecta proposta sem avanço', engine.includes("category: 'proposal_silence'"))
check('motor detecta lead parado', engine.includes("category: 'stale_lead'"))
check('motor detecta meta em risco', engine.includes("category: 'goal_at_risk'"))
check('motor detecta falha de automação', engine.includes("category: 'automation_failure'"))
check('meta usa data local', engine.includes('localDateKey(now)'))
check('horário silencioso atravessa meia-noite', engine.includes('start < end ? current >= start && current < end : current >= start || current < end'))
check('buckets horário/diário existem', engine.includes('notificationFrequencyBucket'))
check('Central usa motor único', center.includes('buildNotificationAlerts'))
check('contador da Topbar usa motor único', topbar.includes('buildNotificationAlerts'))
check('Central respeita canal interno', center.includes('notifications.inAppEnabled'))
check('Central oferece acesso a Configurações', center.includes("navigate('settings', { filter: 'notifications' })"))
check('watcher browser existe', exists('src/features/experience/browser-notification-watcher.tsx') && watcher.includes('BrowserNotificationWatcher'))
check('watcher exige permissão real', watcher.includes("Notification.permission !== 'granted'"))
check('watcher respeita horário silencioso', watcher.includes('isNotificationQuietTime'))
check('watcher deduplica alertas', watcher.includes('realtalent-browser-notifications:') && watcher.includes('seen.has'))
check('watcher usa lembrete específico da Agenda', watcher.includes('agendaReminderMinutes(event)'))
check('watcher abre rota ao clicar', watcher.includes('item.onclick') && watcher.includes('navigate(route, context)'))
check('AppShell usa novo watcher', shell.includes('<BrowserNotificationWatcher />'))
check('Configurações tem aba Notificações', settings.includes("'notifications'") && settings.includes("label: 'Notificações'"))
check('deep link abre aba notificações', (settings.includes("app.routeContext.filter === 'notifications'") || settings.includes("'notifications'") && settings.includes('app.routeContext.filter')))
check('canal CRM marcado funcional', settings.includes('<strong>No CRM</strong>') && settings.includes('Funcional'))
check('canal navegador expõe permissão', settings.includes('Notification.requestPermission()'))
check('e-mail não é simulado como pronto', settings.includes('<strong>E-mail</strong>') && settings.includes('Depende de integração'))
check('WhatsApp não é simulado como pronto', settings.includes('<strong>WhatsApp</strong>') && settings.includes('Planejado'))
check('Pipeline não é simulado sem event log', settings.includes('<strong>Alteração no Pipeline</strong>') && settings.includes('Não simulado'))
check('UI configura frequência', settings.includes('Frequência do navegador'))
check('UI configura horário silencioso', settings.includes('Horário silencioso'))
check('UI configura proposta sem avanço', settings.includes('Proposta sem avanço'))
check('auditoria funcional promove notificações', audit.includes("id: 'notifications', area: 'Administração', name: 'Notificações', status: 'functional'"))
check('CSS dos canais existe', css.includes('.notification-channel-grid') && css.includes('.notification-channel-card'))
check('CSS das regras existe', css.includes('.notification-rule-grid') && css.includes('.notification-rule-card'))
check('teste do motor existe', tests.includes("describe('notification engine'"))
check('teste cobre horário silencioso', tests.includes('respeita horário silencioso atravessando a meia-noite'))
check('teste cobre buckets', tests.includes('gera buckets diferentes para frequência horária e diária'))
check('sem migration V100.83', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => /100[_-]?83/i.test(name)))
check('release notes existem', exists('RELEASE_NOTES_V100.83.0.md'))
check('documentação existe', exists('docs/V100.83.0-NOTIFICACOES-2.0.md'))
check('npm check inclui V100.83', String(pkg.scripts['check:legacy']).includes('qa:v100.83.0'))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`)
if (failed.length) {
  console.error(`\nV100.83.0 Notificações 2.0 audit falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.83.0 Notificações 2.0: ${checks.length}/${checks.length} contratos aprovados.`)
