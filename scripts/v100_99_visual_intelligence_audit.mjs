import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const exists = (file) => fs.existsSync(path.join(root, file))
const checks = []
const check = (label, pass) => checks.push({ label, pass: Boolean(pass) })
const versionAtLeast = (current, baseline) => { const a=String(current).split('.').map(Number); const b=String(baseline).split('.').map(Number); for(let i=0;i<Math.max(a.length,b.length);i+=1){const x=a[i]??0,y=b[i]??0;if(x>y)return true;if(x<y)return false}return true }

const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const health = JSON.parse(read('public/health.json'))
const runtime = JSON.parse(read('public/runtime-version.json'))
const version = read('src/lib/app-version.ts')
const metrics = read('src/features/metrics/metrics-page.tsx')
const visualFunnel = read('src/features/metrics/visual-funnel.tsx')
const css = read('src/styles/visual-intelligence-v10099.css')
const main = read('src/main.tsx')
const launcher = ((read('start-linux.sh') + '\n' + (fs.existsSync('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (fs.existsSync('scripts/start.mjs') ? read('scripts/start.mjs') : '')) + '\n' + (exists?.('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (exists?.('scripts/start.mjs') ? read('scripts/start.mjs') : ''))
const preflight = read('scripts/linux-release-preflight.mjs')

check('package preserva V100.99.0 ou posterior', versionAtLeast(pkg.version, '100.99.0'))
check('package-lock acompanha versão', lock.version === pkg.version && lock.packages?.['']?.version === pkg.version)
check('VERSION acompanha package', read('VERSION').trim() === `V${pkg.version}`)
check('APP_VERSION acompanha package', version.includes(`APP_VERSION = '${pkg.version}'`))
check('health acompanha release atual', health.version === pkg.version && Boolean(health.release))
check('runtime preserva porta CRM isolada', runtime.version === pkg.version && Number(runtime.default_port) >= 4184)
check('runtime preserva Connect 3001', runtime.connect_port === 3001)
check('index identifica release RealTalent atual', read('index.html').includes(`V${pkg.version}`))

check('componente VisualFunnel existe', exists('src/features/metrics/visual-funnel.tsx'))
check('CSS Visual Intelligence existe', exists('src/styles/visual-intelligence-v10099.css'))
check('CSS Visual Intelligence importado', main.includes("./styles/visual-intelligence-v10099.css"))
check('CSS Calling 3.0 continua importado', main.includes("./styles/calling-workspace.css") && read('src/styles/calling-workspace.css').includes(read('src/styles/calling-workspace.css').trim()))
check('Metrics usa VisualFunnel', metrics.includes('<VisualFunnel'))
check('Metrics integra StageModal', metrics.includes('<StageModal'))
check('Metrics mantém leitura detalhada', metrics.includes('Leitura detalhada'))
check('Metrics permite abrir Pipeline', metrics.includes("onOpenPipeline={() => navigate('pipeline')}"))
check('Metrics permite abrir negócio no Pipeline', metrics.includes("action: 'deal-inspector'"))

check('troca de aba usa showTab', metrics.includes('const showTab = (nextTab: MetricsTab)'))
check('troca de aba reposiciona visualização', metrics.includes('scrollIntoView'))
check('troca respeita reduced motion', metrics.includes("prefers-reduced-motion: reduce"))
check('nav recebe ref de âncora', metrics.includes('ref={visualizationAnchorRef}'))
check('nav preserva navegação analítica', metrics.includes('metrics-view-tabs--sticky') || metrics.includes('WorkspaceViewStrip') || metrics.includes('metrics-section-nav-v10171'))
check('CSS sticky possui scroll-margin', css.includes('scroll-margin-top'))
check('CSS sticky possui position sticky', css.includes('position: sticky'))

check('funil calcula largura proporcional', visualFunnel.includes('item.reachedCount / maxReached * 100') || visualFunnel.includes('metricValue / metricMax * 100'))
check('funil mantém largura mínima segura', visualFunnel.includes('Math.max(42') || visualFunnel.includes('Math.max(34') || visualFunnel.includes('Math.max(5'))
check('funil possui animação de hover', css.includes('.metrics-visual-funnel__segment:hover'))
check('funil possui estado ativo', css.includes('.metrics-visual-funnel__segment.is-active'))
check('funil usa clip-path realista', css.includes('clip-path: polygon'))
check('funil possui transição de largura', css.includes('transition: width'))
check('funil reage a hover', visualFunnel.includes('onMouseEnter'))
check('funil reage a teclado', visualFunnel.includes('onFocus'))
check('funil fixa etapa por clique', visualFunnel.includes('onClick={() => onSelectStage(item.stage.id)}'))
check('funil expõe conversão', visualFunnel.includes('conversionFromPrevious'))
check('funil expõe probabilidade', visualFunnel.includes('active.stage.probability'))
check('funil expõe valor da etapa', visualFunnel.includes('formatCurrency(active.value)'))
check('funil expõe tempo médio', visualFunnel.includes('active.avgDays.toFixed(1)'))
check('funil expõe oportunidades paradas', visualFunnel.includes('active.stalled'))
check('funil lista negócios da etapa', visualFunnel.includes('Negócios nesta etapa'))
check('funil permite editar etapa', visualFunnel.includes('onEditStage(active.stage)'))
check('edição reutiliza regras oficiais do Pipeline', metrics.includes("import { StageModal } from '../pipeline/stage-modal'"))

check('layout visual possui painel de detalhes', css.includes('metrics-visual-funnel__detail'))
check('layout visual é responsivo', css.includes('@media (max-width: 820px)'))
check('layout visual respeita reduced motion', css.includes('@media (prefers-reduced-motion: reduce)'))
check('tabela detalhada realça etapa selecionada', css.includes('article.is-selected') || css.includes('button.is-selected'))

check('launcher usa porta isolada atual', launcher.includes('PORT="${PORT:-') && launcher.includes(String(runtime.default_port)))
check('launcher usa release versionada', launcher.includes(pkg.version))
check('launcher mantém RealTalent Connect', launcher.includes('realtalent-connect-server.mjs'))
check('launcher mantém preflight', launcher.includes('linux-release-preflight.mjs'))
check('launcher mantém build real', launcher.includes('npm run build') || launcher.includes('npm run release:verify'))
check('launcher valida release atual', launcher.includes(`V${pkg.version}`))
check('preflight valida V100.99', preflight.includes('V100.99'))

check('release notes existem', exists('RELEASE_NOTES_V100.99.0.md'))
check('documentação existe', exists('docs/V100.99-VISUAL-INTELLIGENCE.md'))
check('script QA registrado', pkg.scripts['qa:v100.99.0'] === 'node scripts/v100_99_visual_intelligence_audit.mjs')
check('npm check inclui V100.99', String(pkg.scripts['check:legacy']).includes('qa:v100.99.0'))

for (const item of checks) console.log(`${item.pass ? 'OK' : 'FAIL'}  ${item.label}`)
const failed = checks.filter((item) => !item.pass)
if (failed.length) {
  console.error(`\nV100.99.0 Visual Intelligence falhou: ${checks.length - failed.length}/${checks.length}.`)
  process.exit(1)
}
console.log(`\nV100.99.0 Visual Intelligence: ${checks.length}/${checks.length} contratos aprovados.`)
