import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

const root=process.cwd()
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const bytes=p=>fs.readFileSync(path.join(root,p))
const exists=p=>fs.existsSync(path.join(root,p))
const json=p=>JSON.parse(read(p))
const checks=[]
const ok=(label,value)=>checks.push({label,ok:Boolean(value)})

const pkg=json('package.json')
const manifest=json('release-manifest.json')
const css=read('src/styles/login-experience.css')
const mark=read('src/components/ui/realtalent-brand-mark.tsx')
const authPage=read('src/features/auth/auth-page.tsx')
const auth=read('src/features/auth/auth-context.tsx')
const app=read('src/app/app.tsx')
const sidebar=read('src/components/layout/sidebar.tsx')
const start=read('scripts/start.mjs')
const index=read('index.html')
const changelog=read('CHANGELOG.md')
const webmanifest=json('public/manifest.webmanifest')
const logo=bytes('public/realtalent-logo.png')
const logoSha=crypto.createHash('sha256').update(logo).digest('hex')
const pngWidth=logo.readUInt32BE(16)
const pngHeight=logo.readUInt32BE(20)

ok('package preserves 101.11.1 semver for H3',['101.11.1','101.11.2','101.11.3'].includes(pkg.version))
ok('manifest identifies H3 official logo motion',(((manifest.release?.hotfix==='H3'&&manifest.release?.hotfixName==='Official Logo Motion'&&manifest.release?.hotfixBaseRelease==='V101.11.1-H2')||(manifest.release?.hotfix==='H4'&&manifest.release?.hotfixBaseRelease==='V101.11.1-H3')||(manifest.release?.hotfix==='H5'&&manifest.release?.hotfixBaseRelease==='V101.11.1-H4'))||(manifest.release?.version==='101.11.2'&&manifest.release?.baseRelease==='V101.11.1-H5')||(manifest.release?.version==='101.11.3'&&manifest.release?.baseRelease==='V101.11.2')))
ok('H3 introduces no database migration',manifest.migrations?.expectedCount>=49&&json('supabase/migrations.lock.json').migrations.length>=49)
ok('official uploaded logo asset has exact expected SHA-256',logoSha==='29861b7c31f5b0931d2afe065e057cdf0de6ffc56a95abd0d24971670a98fb5f')
ok('official uploaded logo dimensions are preserved',pngWidth===102&&pngHeight===103)
ok('brand mark renders official logo asset',mark.includes('/realtalent-logo.png')||mark.includes('/realtalent-logo-transparent.png'))
ok('logo remains the animated object',mark.includes('rt-brand-mark__frame')&&mark.includes('rt-brand-mark__scan')&&mark.includes('rt-brand-mark__pulse'))
ok('H3 CSS marker is present',css.startsWith('/* V101.11.1-H3 — Official Logo Motion')||(css.startsWith('/* V101.11.1-H4 — Transparent Logo & Optimized Motion')||css.startsWith('/* V101.11.1-H5 — Full Canvas & Orbit Field')))
ok('logo reveal builds vertically from bottom',css.includes('clip-path: inset(100% 0 0 0 round 24%)')||css.includes('@keyframes rt-bar-rise'))
ok('official logo blue is part of palette',css.includes('--rt-login-blue: #04274b')||css.includes('--rt-login-blue-800: #04274b'))
ok('official logo teal is part of palette',css.includes('--rt-login-green: #098982')||css.includes('--rt-login-teal-500: #098982'))
ok('brand halo is recalibrated to official teal',css.includes('rgba(9,137,130,.18)')||css.includes('rgba(9,137,130,.34)'))
ok('auth background remains full-screen blue/teal',(css.includes('linear-gradient(132deg, #031522')&&css.includes('#062b49')&&css.includes('#052b43'))||(css.includes('linear-gradient(132deg, #020d18')&&css.includes('#04274b')&&css.includes('#052b43')))
ok('primary action follows official blue/teal gradient',css.includes('#098982 100%')||css.includes('#1d9e75 100%'))
ok('HTML theme color follows official blue',index.includes('<meta name="theme-color" content="#04274b"'))
ok('PWA theme color follows official blue',webmanifest.theme_color==='#04274b'&&webmanifest.background_color==='#041827')
ok('H2 full-screen login remains preserved',css.includes('.rt-splash,\n.auth-page')&&authPage.includes('auth-page__mesh'))
ok('H1 local login gate remains preserved',authPage.includes('Abrir workspace local')&&authPage.includes('await auth.enterLocal()'))
ok('H1 local session remains sessionStorage-backed',auth.includes('window.sessionStorage.getItem')&&auth.includes('window.sessionStorage.setItem'))
ok('logout remains visible',sidebar.includes('Sair da conta')&&sidebar.includes('onClick={() => void signOut()}'))
ok('workspace remains gated behind user',app.includes('if (!user || recoveryMode) return <AuthPage />'))
ok('Supabase password authentication remains intact',auth.includes('client.auth.signInWithPassword'))
ok('reduced motion remains supported',css.includes('@media (prefers-reduced-motion: reduce)')&&css.includes('.rt-brand-mark--animated .rt-brand-mark__scan'))
ok('H3 runtime requires H1 H2 H3 markers',start.includes("includes('V101.11.1-H1 — Login Gate & Logout')")&&start.includes("includes('V101.11.1-H2 — Cinematic Login & Brand Motion')")&&start.includes("includes('V101.11.1-H3 — Official Logo Motion')"))
ok('H3 runtime migrates state from H2 first',start.indexOf('RealTalent-CRM-V101.11.1-H2-Cinematic-Login-Brand-Motion-Linux-Launcher')>=0&&start.indexOf('RealTalent-CRM-V101.11.1-H2-Cinematic-Login-Brand-Motion-Linux-Launcher')<start.indexOf('RealTalent-CRM-V101.11.1-H1-Login-Gate-Logout-Linux-Launcher'))
ok('launcher runs H3 QA gate',start.includes("npm(['run', 'qa:v101.11.1:h3'])"))
ok('runtime URL identifies H3 or a verified successor',start.includes('rt_release=101.11.1-h3-official-logo-motion')||start.includes('rt_release=101.11.1-h4-transparent-logo-optimized-motion')||start.includes('rt_release=101.11.1-h5-full-canvas-orbit-field')||(['101.11.2','101.11.3'].includes(pkg.version)&&(start.includes('rt_release=101.11.3-h1-communications-gateway-recovery')||start.includes('rt_release=101.11.3-h2-runtime-service-recovery'))&&start.includes("'V101.11.1-H3 — Official Logo Motion'")))
ok('index carries H3 lineage marker',index.includes('V101.11.1-H3 — Official Logo Motion'))
ok('changelog documents H3 first',changelog.includes('# V101.11.1-H3 — Official Logo Motion'))
ok('H3 QA gate is registered',pkg.scripts?.['qa:v101.11.1:h3']==='node scripts/v101_11_1_h3_official_logo_motion_audit.mjs')
ok('H3 QA gate is in architecture',pkg.scripts?.['qa:architecture']?.includes('qa:v101.11.1:h3'))
ok('manifest requires H3 QA gate',manifest.qa?.requiredGates?.includes('qa:v101.11.1:h3'))
ok('H3 release notes exist',exists('RELEASE_NOTES_V101.11.1-H3.md'))

for(const item of checks) console.log(`${item.ok?'OK  ':'FAIL'} ${item.label}`)
const failed=checks.filter(item=>!item.ok)
console.log(`\nV101.11.1-H3 Official Logo Motion: ${checks.length-failed.length}/${checks.length} contracts.`)
if(failed.length) process.exit(1)
