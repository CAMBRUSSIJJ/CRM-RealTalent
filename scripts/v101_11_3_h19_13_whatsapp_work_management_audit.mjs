import fs from 'node:fs'
import path from 'node:path'
const ROOT=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..')
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8')
const page=read('src/features/communications/communications-page.tsx')
const chat=read('src/features/communications/whatsapp-chat-panel.tsx')
const toolbar=read('src/features/communications/whatsapp-work-toolbar.tsx')
const work=read('src/services/whatsapp-work-management.ts')
const css=read('src/styles/communications-v10086.css')
const start=read('scripts/start.mjs')
const manifest=JSON.parse(read('release-manifest.json'))
const health=JSON.parse(read('public/health.json'))
const runtime=JSON.parse(read('public/runtime-version.json'))
const matrix=JSON.parse(read('qa/capability-matrix.json'))
const checks=[]
const conversationOnlySuccessor=page.includes('V101.11.3-H20.7-H2 — WhatsApp Conversation-Only Inbox') && page.includes('communication-focus-inbox--conversations-only')
const ok=(name,cond)=>checks.push([name,Boolean(cond)])
ok('manifest H19.13',manifest.release.buildLabel==='V101.11.3-H19.13' && manifest.release.hotfix==='H19.13')
ok('base H19.12',manifest.release.hotfixBaseRelease==='V101.11.3-H19.12')
ok('launcher marker H19.13',start.includes('h19-13-whatsapp-work-management'))
ok('H19.12 lineage preserved',page.includes('H19.12 lineage'))
ok('Pure Chat lineage preserved',page.includes('V101.11.3-H19.7 — WhatsApp Pure Chat'))
ok('work toolbar injected outside timeline',chat.includes('whatsapp-chat__work-layer') && chat.indexOf('whatsapp-chat__work-layer') < chat.indexOf('whatsapp-chat__messages'))
ok('third CRM column not reintroduced',!page.includes('communication-context-rail') && page.includes('communication-lead-drawer'))
ok('labels service',work.includes('DEFAULT_WHATSAPP_WORK_LABELS') && work.includes('createWhatsAppWorkLabel') && work.includes('deleteWhatsAppWorkLabel'))
ok('operational status service',work.includes("'followup_scheduled'") && work.includes('whatsappOperationalStatusLabel'))
ok('owner assignment',toolbar.includes('Responsável') && toolbar.includes('listWorkspaceMembers'))
ok('task creates real CRM task',toolbar.includes('saveTask(repositoryMode, workspaceId') && toolbar.includes("tags: ['whatsapp', 'comunicacoes']"))
ok('task links lead when available',toolbar.includes("entityType: 'lead'"))
ok('followup creates CRM activity',toolbar.includes('createActivity({') && toolbar.includes("purpose: 'whatsapp_followup'"))
ok('followup updates next action',toolbar.includes('updateLead(lead.id, { nextActionAt: dueAt })'))
ok('work controls preserved under successor UX',(page.includes('Follow-ups hoje') && page.includes('Vencidas') && page.includes('Aguardando cliente') && page.includes('Sem responsável')) || (conversationOnlySuccessor && toolbar.includes('Follow-up') && toolbar.includes('Tarefa') && toolbar.includes('Etiqueta')))
ok('labels preserved under successor UX',(page.includes('whatsappLabelCounts') && page.includes("inboxView.startsWith('label:')")) || (conversationOnlySuccessor && toolbar.includes('labels') && work.includes('DEFAULT_WHATSAPP_WORK_LABELS')))
ok('task bridge preserved under successor UX',(page.includes('overdueTaskLeadIds') && page.includes('Tarefa vencida')) || (conversationOnlySuccessor && toolbar.includes('saveTask(repositoryMode, workspaceId')))
ok('conversation rows respect successor UX',page.includes('whatsapp-conversation-workmeta') || (conversationOnlySuccessor && !page.includes('whatsapp-conversation-workmeta')))
ok('work management CSS',css.includes('V101.11.3-H19.13 — WhatsApp Work Management') && css.includes('.whatsapp-workbar') && css.includes('.whatsapp-work-inbox'))
ok('health exposes H19.13',health.whatsappWorkManagement==='v101.11.3-h19.13' && health.whatsappOperationalInbox==='v101.11.3-h19.13')
ok('runtime exposes H19.13',runtime.whatsappConversationLabels==='v101.11.3-h19.13' && runtime.whatsappTaskFollowupBridge==='v101.11.3-h19.13')
ok('capability matrix registers H19.13',matrix.capabilities?.some(c=>c.id==='communications.whatsapp-work-management-h19.13'&&c.evidence?.some(e=>e.command==='qa:v101.11.3:h19.13')))
ok('quick replies remain absent from chat',!chat.includes('Respostas rápidas'))
ok('legacy proposal remains absent from chat',!chat.includes('Proposta'))
ok('rich media still preserved',chat.includes('whatsapp-chat__attachment-preview'))
ok('voice still preserved',chat.includes('startRecording'))
ok('reply still preserved',chat.includes('replyingTo'))
let pass=0
for (const [name,value] of checks){ console.log(`${value?'OK  ':'FAIL'} ${name}`); if(value)pass++ }
console.log(`\nH19.13 WhatsApp Work Management: ${pass}/${checks.length}`)
if(pass!==checks.length) process.exit(1)
