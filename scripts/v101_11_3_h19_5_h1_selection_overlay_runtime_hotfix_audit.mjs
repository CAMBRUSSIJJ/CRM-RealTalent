import fs from 'node:fs'
const read=(p)=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8')
const checks=[]; const check=(name,ok)=>{checks.push([name,Boolean(ok)]); console.log(`${ok?'OK  ':'FAIL'} ${name}`)}
const canonicalCss=read('src/styles/selection-controls.css')
const hotfixCss=read('src/styles/work-management.css')
const overlays=read('src/styles/experience-system.css')
const selection=read('src/components/selection/selection-system.tsx')
const task=read('src/features/tasks/task-modal.tsx')
const pkg=JSON.parse(read('package.json'))
const manifest=JSON.parse(read('release-manifest.json'))
const canonicalMenuZ=Number(canonicalCss.match(/\.rt-selection-menu-v101105\{z-index:(\d+)/)?.[1] ?? 0)
const menuZ=Number(hotfixCss.match(/V101\.11\.3-H19\.5-H1[^]*?\.rt-selection-menu-v101105\{z-index:(\d+)/)?.[1] ?? 0)
const modalZ=Number(overlays.match(/\.modal-backdrop\s*\{\s*z-index:\s*(\d+)/)?.[1] ?? 0)
check('Selection menu usa portal global',selection.includes('createPortal(menu, document.body)'))
check('CSS canônico da seleção permanece intacto',canonicalMenuZ===9999)
check('Hotfix vive em camada posterior existente',hotfixCss.includes('V101.11.3-H19.5-H1 — Selection Overlay Runtime Fix'))
check('Modal possui camada elevada',modalZ>=13000)
check('Menu de seleção fica acima do modal',menuZ>modalZ)
check('Menu permanece abaixo da região de toast',menuZ<14000)
check('Status conserva opções funcionais',task.includes('<option value="todo">A fazer</option>')&&task.includes('<option value="completed">Concluída</option>'))
check('Prioridade conserva opções funcionais',task.includes('<option value="normal">Normal</option>')&&task.includes('<option value="urgent">Urgente</option>'))
check('Equipe informa ausência de cadastro',task.includes('Nenhuma equipe cadastrada'))
check('Responsável informa ausência de pessoas',task.includes('Nenhuma pessoa disponível'))
check('Equipe continua filtrando responsável',task.includes('selectedTeamMemberIds')&&task.includes('availableMembers'))
check('Checklist continua com checkbox interativo',task.includes('work-checklist-item__check')&&task.includes('completed: !item.completed'))
check('Checklist continua permitindo adicionar item',task.includes('placeholder="Adicionar um item"')&&task.includes('addChecklistItem'))
check('Gate H19.5 base preservado',pkg.scripts?.['qa:v101.11.3:h19.5']?.includes('v101_11_3_h19_5_channel_workspaces_collaborative_tasks_audit.mjs'))
check('Manifest preserva base H19.5-H1 ou sucessora',manifest.release?.hotfix==='H19.5'||(manifest.release?.hotfix==='H19.6'&&manifest.release?.hotfixBaseRelease==='V101.11.3-H19.5-H1'))
check('Manifest preserva lineage do patch H1',manifest.release?.hotfix==='H19.6'?manifest.release?.hotfixBaseRelease==='V101.11.3-H19.5-H1':(manifest.release?.patch==='H1'&&manifest.release?.patchBaseRelease==='V101.11.3-H19.5'))
check('Gate H1 registrado',pkg.scripts?.['qa:v101.11.3:h19.5:h1']?.includes('v101_11_3_h19_5_h1_selection_overlay_runtime_hotfix_audit.mjs'))
check('Gate H1 está na arquitetura',pkg.scripts?.['qa:architecture']?.includes('qa:v101.11.3:h19.5:h1'))
const failed=checks.filter(([,ok])=>!ok)
console.log(`\nH19.5-H1 Selection Overlay Runtime Hotfix: ${checks.length-failed.length}/${checks.length}`)
if(failed.length) process.exit(1)
