import fs from 'node:fs'
const read=(p)=>fs.readFileSync(p,'utf8')
const json=(p)=>JSON.parse(read(p))
const checks=[]
const ok=(name,value)=>{checks.push([name,Boolean(value)]);console.log(`${value?'OK  ':'FAIL'} ${name}`)}
const manifest=json('release-manifest.json')
const main=read('src/main.tsx')
const css=read('src/styles/h20-product-cohesion.css')
const runtime=read('src/platform/design-system/ui-cohesion-runtime.ts')
const shell=read('src/components/workspace/workspace-shell.tsx')
const tasks=read('src/features/tasks/tasks-page.tsx')
const teams=read('src/features/teams/teams-page.tsx')
const followups=read('src/features/followups/followups-page.tsx')
const start=read('scripts/start.mjs')
const health=json('public/health.json')
const runtimeVersion=json('public/runtime-version.json')
const matrix=json('qa/capability-matrix.json')
const cssImports=[...main.matchAll(/import\s+['"]\.\/styles\/([^'"]+\.css)['"]/g)].map(m=>m[1])
ok('functional lineage remains H19.13',manifest.release?.buildLabel==='V101.11.3-H19.13'&&manifest.release?.hotfix==='H19.13')
ok('H20.3 UI foundation preserved',manifest.uiCohesion?.baseRelease==='V101.11.3-H19.13'&&manifest.uiCohesion?.phases?.includes('H20.3 Global Workspace Shell'))
ok('H20 successor artifacts registered',(manifest.uiArtifacts?.linuxLauncher?.includes('H20.5-Settings-Calling-Cohesion')||manifest.uiArtifacts?.linuxLauncher?.includes('H20.6-Core-Sales-Workspace-Cohesion')||manifest.uiArtifacts?.linuxLauncher?.includes('H20.7-Global-UI-Final-Pass')))
ok('H20 stylesheet remains final global stylesheet',cssImports.at(-1)==='h20-product-cohesion.css')
ok('runtime CSS budget remains bounded',cssImports.length<=52)
ok('interaction brand is canonical blue',css.includes('--rt-color-brand:#315BD8')&&css.includes('--rt-color-brand-hover:#274CC5'))
ok('green is semantic success only',css.includes('--rt-color-success:#1D9E75')&&css.includes('--accent:var(--rt-color-brand)'))
ok('semantic legacy aliases resolve to canonical brand',css.includes('--blue:var(--rt-color-brand)')&&css.includes('--primary:var(--rt-color-brand)'))
ok('workspace shell exports header',shell.includes('export function WorkspacePageHeader'))
ok('workspace shell exports summary strip',shell.includes('export function WorkspaceSummaryStrip')&&shell.includes('WorkspaceSummaryMetric'))
ok('workspace shell exports view strip',shell.includes('export function WorkspaceViewStrip'))
ok('workspace shell exports command bar',shell.includes('export function WorkspaceCommandBar'))
ok('Tasks migrated to H20 shell',tasks.includes('WorkspacePageHeader')&&tasks.includes('WorkspaceSummaryStrip')&&tasks.includes('WorkspaceViewStrip')&&tasks.includes('WorkspaceCommandBar'))
ok('Teams migrated to H20 shell',teams.includes('WorkspacePageHeader')&&teams.includes('WorkspaceViewStrip'))
ok('Follow-ups migrated to H20 shell',followups.includes('WorkspacePageHeader')&&followups.includes('WorkspaceSummaryStrip')&&followups.includes('WorkspaceViewStrip'))
ok('Follow-ups retains advanced filter drawer',followups.includes('followup-filter-drawer-v10167')&&followups.includes('WorkspaceFilterMenu'))
ok('old Tasks/Teams alternate header is neutralized',css.includes('.tasks-page-v101112 .work-page-header,.teams-page-v101112 .work-page-header{display:none}'))
ok('runtime cascade guard installed',main.includes('installUiCohesionRuntime()')&&runtime.includes('MutationObserver')&&runtime.includes('rt-h20-cascade-guard'))
ok('runtime guard reasserts canonical tokens',runtime.includes("'--rt-color-brand': '#315BD8'")&&runtime.includes("'--rt-color-success': '#1D9E75'"))
ok('runtime URL exposes H20 successor marker',(start.includes('rt_cohesion=101.11.3-h20-5-settings-calling-cohesion')||start.includes('rt_cohesion=101.11.3-h20-6-core-sales-workspace-cohesion')||start.includes('rt_cohesion=101.11.3-h20-7-global-ui-final-pass')))
ok('health exposes H20.1-H20.3 foundation',health.designSystemTruth==='v101.11.3-h20.1'&&health.cssCascadeRecovery==='v101.11.3-h20.2'&&health.globalWorkspaceShell==='v101.11.3-h20.3')
ok('runtime version preserves H20 shell stage',runtimeVersion.globalWorkspaceShell==='v101.11.3-h20.3')
ok('capability matrix registers UI cohesion',matrix.capabilities.some(c=>c.id==='platform.ui-cohesion'&&c.evidence?.some(e=>e.command==='qa:v101.11.3:h20.3')))
ok('H19.13 WhatsApp work layer remains present',read('src/features/communications/communications-page.tsx').includes('V101.11.3-H19.13'))
ok('no new migration introduced',Number(manifest.migrations?.expectedCount)>=54)
const tiny=[...css.matchAll(/font-size:\s*([0-9.]+)px/g)].map(m=>Number(m[1])).filter(n=>n<10)
ok('H20 canonical stylesheet contains no sub-10px typography',tiny.length===0)
const failed=checks.filter(([,v])=>!v)
console.log(`\nH20.3 Global UI & Product Cohesion: ${checks.length-failed.length}/${checks.length}`)
if(failed.length) process.exit(1)
