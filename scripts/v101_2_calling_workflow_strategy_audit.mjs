import fs from 'node:fs'
import path from 'node:path'

const root=process.cwd()
const read=(file)=>fs.readFileSync(path.join(root,file),'utf8')
const exists=(file)=>fs.existsSync(path.join(root,file))
const checks=[]
const check=(label,pass)=>checks.push({label,pass:Boolean(pass)})

const pkg=JSON.parse(read('package.json'))
const lock=JSON.parse(read('package-lock.json'))
const health=JSON.parse(read('public/health.json'))
const runtime=JSON.parse(read('public/runtime-version.json'))
const appVersion=read('src/lib/app-version.ts')
const index=read('index.html')
const main=read('src/main.tsx')
const strategy=read('src/services/calling-strategy.ts')
const playbooks=read('src/features/playbooks/playbooks-page.tsx')
const prep=read('src/features/calls/call-session-preparation-modal.tsx')
const workspace=read('src/features/calls/call-workspace-modal.tsx')
const dialer=read('src/services/voice-dialer.ts')
const voiceSettings=read('src/features/calls/voice-dialer-settings-modal.tsx')
const connect=read('scripts/realtalent-connect-server.mjs')
const phoneCompanion=exists('scripts/realtalent-phone-v10183.html')?read('scripts/realtalent-phone-v10183.html'):connect
const launcher=((read('start-linux.sh') + '\n' + (fs.existsSync('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (fs.existsSync('scripts/start.mjs') ? read('scripts/start.mjs') : '')) + '\n' + (exists?.('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (exists?.('scripts/start.mjs') ? read('scripts/start.mjs') : ''))
const styles=read('src/styles/calling-workspace.css')

check('baseline V101.2 preservada',Number(pkg.version.split('.')[0])>101||(Number(pkg.version.split('.')[0])===101&&Number(pkg.version.split('.')[1])>=2))
check('lock acompanha pacote',lock.version===pkg.version&&lock.packages?.['']?.version===pkg.version)
check('VERSION acompanha pacote',read('VERSION').trim()===`V${pkg.version}`)
check('APP_VERSION acompanha pacote',appVersion.includes(`APP_VERSION = '${pkg.version}'`))
check('backup schema preservado',appVersion.includes("BACKUP_SCHEMA_VERSION = '100.54'"))
check('health acompanha pacote',health.version===pkg.version)
check('runtime acompanha pacote',runtime.version===pkg.version)
check('runtime usa porta moderna',runtime.default_port>=4187)
check('index preserva identidade RealTalent',index.includes('RealTalent CRM V101.'))
check('CSS V101.2 importado', main.includes("./styles/calling-workspace.css") && read('src/styles/calling-workspace.css').includes(styles.trim()))

check('Strategy schema versionado',strategy.includes("CALLING_STRATEGY_SCHEMA = 'realtalent.calling.strategy.v1'"))
for(const field of ['autoSelectPlaybook','defaultPlaybookId','defaultObjective','defaultSessionMode','showAssistantDuringCall','showHistoryOnDemand','autosaveNotes','healthAlertsOnly']) check(`Strategy persiste ${field}`,strategy.includes(field))
check('rascunho de nota por lead',strategy.includes('call-note-draft:v1012')&&strategy.includes('saveCallNoteDraft')&&strategy.includes('clearCallNoteDraft'))

check('Playbooks possui Strategy Hub',playbooks.includes('Strategy Hub · V101.2')&&playbooks.includes("setView('strategy')"))
check('Strategy Hub liga objetivo',playbooks.includes('Objetivo padrão')&&playbooks.includes('CALL_SESSION_OBJECTIVES'))
check('Strategy Hub liga modo',playbooks.includes('Modo padrão')&&playbooks.includes('Power assistido'))
check('Strategy Hub controla roteiro automático',playbooks.includes('autoSelectPlaybook')&&playbooks.includes('defaultPlaybookId'))
check('Strategy Hub controla foco de tela',playbooks.includes('showAssistantDuringCall')&&playbooks.includes('healthAlertsOnly'))
check('deep-link de estratégia',playbooks.includes("routeContext.filter !== 'strategy'"))

check('preparação tem Roteiro da sessão',prep.includes('Roteiro da sessão')&&prep.includes('Trocar roteiro'))
check('preparação abre Strategy Hub',prep.includes("navigate('playbooks', { filter: 'strategy' })"))
check('preparação usa estratégia salva',prep.includes('readCallingStrategyPreferences'))
check('preparação tem seletor visual',prep.includes('call-preparation-v1012__route-picker'))
check('preparação reduz zero-state de validação',prep.includes('Fila pronta para ligar'))
check('preparação esconde next quando fila unitária',prep.includes('orderedSessionLeads.length > 1'))

check('Modo Foco possui contexto progressivo',workspace.includes('Contexto, histórico e anotações'))
check('Modo Foco possui resumo',workspace.includes("contextTab === 'summary'")&&workspace.includes('calling-v1012__summary-grid'))
check('Modo Foco possui histórico',workspace.includes("contextTab === 'history'")&&workspace.includes('recentHistory'))
check('Modo Foco possui notas',workspace.includes("contextTab === 'notes'")&&workspace.includes('calling-v1012__notes'))
check('notas possuem autosave',workspace.includes('saveCallNoteDraft')&&workspace.includes('strategy.autosaveNotes'))
check('nota importante pode ser fixada',workspace.includes('pinImportantNote')&&workspace.includes('pinned_call_note'))
check('Assistant pode ser ocultado',workspace.includes('strategy.showAssistantDuringCall')&&workspace.includes('calling-v1012__conversation--no-assistant'))
check('Call Health é condicional',workspace.includes('strategy.healthAlertsOnly'))
check('RealTalent Phone descrito no Modo Foco',workspace.includes("startsWith('connect:phone:')")&&workspace.includes('RealTalent Phone'))
check('término de phone não promete desligar SIM',workspace.includes('Registrar término'))

check('Voice Dialer descobre phones',dialer.includes('/api/phone/v1/devices')&&dialer.includes('connect:phone:'))
check('Voice Dialer busca pareamento',dialer.includes('/api/phone/v1/pairing')&&dialer.includes('fetchRealTalentPhonePairing'))
check('Settings exibe companion',voiceSettings.includes('Celular pareado ao Connect')&&voiceSettings.includes('Código de pareamento'))
check('Settings seleciona device phone',voiceSettings.includes('selectedDeviceId: device.id'))

check('Connect escuta LAN',connect.includes("REALTALENT_CONNECT_HOST || '0.0.0.0'"))
check('Connect mantém Voice API v1',connect.includes("CAP_SCHEMA = 'realtalent.voice.capabilities.v1'")&&connect.includes("CALL_SCHEMA = 'realtalent.voice.call.v1'"))
check('Connect possui Phone schema',connect.includes("PHONE_SCHEMA = 'realtalent.phone.v1'"))
for(const endpoint of ['/phone','/api/phone/v1/pairing','/api/phone/v1/pair','/api/phone/v1/poll','/api/phone/v1/state','/api/phone/v1/devices']) check(`Connect possui ${endpoint}`,connect.includes(endpoint))
check('Phone abre discador nativo',phoneCompanion.includes("location.href='tel:'"))
check('Phone explicita limite do SIM',connect.includes('não consegue controlar uma chamada SIM nativa')||phoneCompanion.includes('O iOS ainda pode exigir a confirmação final')||phoneCompanion.includes('O iOS ainda controla a confirmação final'))
check('Connect preserva Twilio Agent Bridge',connect.includes('createTwilioCall')&&connect.includes('twilio_bridge'))
check('Connect protege Voice API por origem',connect.includes('isOriginAllowed')&&connect.includes('Origem não autorizada'))
check('lista phone remove token',connect.includes('map(({ token, ...device })'))
check('pareamento phone persiste localmente',connect.includes('.realtalent-phone-devices.json')&&connect.includes('persistPhoneDevices')&&connect.includes('loadPhoneDevices'))

check('CSS cobre route picker',styles.includes('.call-preparation-v1012__route-picker'))
check('CSS cobre contexto',styles.includes('.calling-v1012__context-tabs'))
check('CSS cobre companion',styles.includes('.voice-settings-v1012__pairing'))
check('CSS responsivo',styles.includes('@media (max-width:720px)'))

check('launcher preserva baseline moderna',launcher.includes('RealTalent CRM V101.'))
check('launcher usa porta moderna',/PORT=\"\$\{PORT:-41(87|88|89|90)\}\"/.test(launcher))
check('launcher expõe Connect na LAN',launcher.includes('REALTALENT_CONNECT_HOST=0.0.0.0'))
check('launcher possui release channel',launcher.includes('VITE_RELEASE_CHANNEL='))
check('launcher serve build validado',launcher.includes('vite preview'))
check('QA V101.2 registrado',pkg.scripts['qa:v101.2.0']==='node scripts/v101_2_calling_workflow_strategy_audit.mjs')
check('check inclui V101.2',String(pkg.scripts['check:legacy']).includes('qa:v101.2.0'))
check('runtime bundle registrado',Boolean(pkg.scripts['runtime:bundle']))
check('runtime HTTP registrado',Boolean(pkg.scripts['runtime:http']))
check('runtime Connect V101.2 preservado/evoluído',['node scripts/v101_2_connect_smoke.mjs','node scripts/v101_4_connect_resilience_smoke.mjs'].includes(pkg.scripts['runtime:connect']))
check('release verify inclui Connect smoke',String(pkg.scripts['release:verify']).includes('runtime:connect'))
check('release notes V101.2 existem',exists('RELEASE_NOTES_V101.2.0.md'))
check('documentação V101.2 existe',exists('docs/V101.2-CALLING-WORKFLOW-STRATEGY.md'))

for(const item of checks) console.log(`${item.pass?'OK':'FAIL'}  ${item.label}`)
const failed=checks.filter((item)=>!item.pass)
if(failed.length){console.error(`\nV101.2.0 Calling Workflow & Strategy falhou: ${checks.length-failed.length}/${checks.length}.`);for(const item of failed)console.error(`- ${item.label}`);process.exit(1)}
console.log(`\nV101.2.0 Calling Workflow & Strategy: ${checks.length}/${checks.length} contratos aprovados.`)
