#!/usr/bin/env node
import fs from 'node:fs'
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8')
const exists=p=>fs.existsSync(new URL(`../${p}`,import.meta.url))
const bridge=read('scripts/whatsapp-browser-qr-bridge.mjs')
const gateway=read('scripts/realtalent-communications-gateway.mjs')
const start=((read('start-linux.sh') + '\n' + (fs.existsSync('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (fs.existsSync('scripts/start.mjs') ? read('scripts/start.mjs') : '')) + '\n' + (exists?.('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (exists?.('scripts/start.mjs') ? read('scripts/start.mjs') : ''))
const index=read('index.html')
const pkg=JSON.parse(read('package.json'))
const checks=[]
const ok=(name,v)=>{checks.push([name,Boolean(v)]);console.log(`${v?'OK  ':'FAIL'} ${name}`)}
ok('gateway identifica H13', gateway.includes("const VERSION = '101.8.4-h13'"))
ok('bridge lê WAWebCollections diretamente', bridge.includes("window.require('WAWebCollections')")&&bridge.includes('fetchRawStoreChats'))
ok('bridge lê Chat collection sem serialize completo', bridge.includes('chatCollection')&&bridge.includes('getModelsArray')&&!bridge.slice(bridge.indexOf('fetchRawStoreChats'), bridge.indexOf('async function fetchChatsWithRetry')).includes('chat.serialize'))
ok('bridge lê mensagens materializadas', bridge.includes('asArray(chat?.msgs)'))
ok('ID moderno $1 é suportado', bridge.includes('value?.$1'))
ok('store direta é caminho primário', bridge.indexOf('fetchRawStoreChats(session') < bridge.indexOf('session.client.getChats()'))
ok('getChats permanece fallback', bridge.includes("mode: 'wwebjs-getChats'"))
ok('diagnóstico registra engine do histórico', bridge.includes('historyEngine'))
ok('importador entende chats raw', bridge.includes('chat?.__rawStore'))
ok('importação inicial aguarda materialização', bridge.includes('}, 5000).unref?.()'))
ok('launcher identifica H13', start.includes('V101.8.4-H13 — WhatsApp Real History Bridge'))
ok('launcher migra H12 para H13', start.includes('RealTalent-CRM-V101.8.4-H12-WhatsApp-Realtime')&&start.includes('Sessão de comunicações encontrada na versão anterior.'))
ok('health exige H13', start.includes("j.version!=='101.8.4-h13'"))
ok('index identifica H13', index.includes('V101.8.4-H13 — WhatsApp Real History Bridge'))
ok('release notes H13 existem', exists('RELEASE_NOTES_V101.8.4-H13.md'))
ok('diagnóstico mede store real sem expor conteúdo', bridge.includes('materializedMessageCount')&&bridge.includes('chatCount')&&gateway.includes('/api/integrations/whatsapp/qr/diagnostics'))
ok('package preserva whatsapp-web.js 1.34.7', pkg.dependencies?.['whatsapp-web.js']==='1.34.7')
const failed=checks.filter(([,v])=>!v)
console.log(`\nV101.8.4-H13 WhatsApp Real History Bridge: ${checks.length-failed.length}/${checks.length} contratos aprovados.`)
if(failed.length) process.exit(1)
