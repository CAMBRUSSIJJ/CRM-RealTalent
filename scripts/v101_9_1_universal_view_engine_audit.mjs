import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8')
const exists = (name) => fs.existsSync(path.join(root, name))
const pkg = JSON.parse(read('package.json'))
const checks = []
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) })

const definition = read('src/platform/views/view-definition.ts')
const ast = read('src/platform/views/filter-ast.ts')
const engine = read('src/platform/views/view-engine.ts')
const store = read('src/platform/views/view-store.ts')
const adapters = read('src/platform/views/legacy-view-adapters.ts')
const inspector = read('src/platform/views/view-inspector.ts')
const contacts = read('src/services/contact-saved-views-v10161.ts')
const pipeline = read('src/features/pipeline/pipeline-preferences.ts')
const fields = read('src/platform/metadata/field-registry.ts')
const main = read('src/main.tsx')
const version = read('src/lib/app-version.ts')
const launcher = ((read('start-linux.sh') + '\n' + (fs.existsSync('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (fs.existsSync('scripts/start.mjs') ? read('scripts/start.mjs') : '')) + '\n' + (exists?.('start-linux-legacy.sh') ? read('start-linux-legacy.sh') : '') + '\n' + (exists?.('scripts/start.mjs') ? read('scripts/start.mjs') : ''))
const tests = read('src/platform/views/universal-view-engine.test.ts')

check('package mantém ou sucede ciclo 101.9.x', /^101\.(?:9|10|11)\./.test(pkg.version))
check('APP_VERSION acompanha release sucessora do ciclo 101.9.x', version.includes(`APP_VERSION = '${pkg.version}'`) && version.includes(`APP_VERSION_LABEL = 'V${pkg.version}'`))
check('ViewDefinition persistente existe', exists('src/platform/views/view-definition.ts') && definition.includes("schemaVersion: '101.9.1'") && definition.includes('visibility: ViewVisibility'))
check('modos Table/List/Kanban/Calendar existem', ['table','list','kanban','calendar'].every((mode) => definition.includes(`'${mode}'`)))
check('AST suporta AND/OR/NOT', ast.includes("FilterLogicalOperator = 'and' | 'or'") && ast.includes("kind: 'not'"))
check('operadores são validados por FieldKind', ast.includes('operatorMatrix') && ast.includes('filterOperatorsForKind') && ast.includes('unsupported_operator'))
check('View Engine executa filtro, sort e grouping', engine.includes('evaluateAst') && engine.includes('compareWithSort') && engine.includes('groupRecords') && engine.includes('executeView'))
check('View Store persiste personal/workspace', store.includes('safeStorage') && store.includes("visibility === 'workspace'") && store.includes('saveUniversalView'))
check('View Store isola identidade por surface + id', store.includes('sameIdentity') && store.includes('left.surface === right.surface'))
check('projeções removem views órfãs por superfície', contacts.includes('replaceSurfaceUniversalViews') && pipeline.includes('replaceSurfaceUniversalViews'))
check('adapter legado de Contatos existe', adapters.includes('contactSavedViewToUniversal') && adapters.includes("surface: 'contacts'"))
check('adapter legado de Pipeline existe', adapters.includes('pipelineSavedViewToUniversal') && adapters.includes("surface: 'pipeline'"))
check('Contatos sincroniza ViewDefinition universal', contacts.includes('contactSavedViewToUniversal') && contacts.includes('saveUniversalView'))
check('Pipeline sincroniza ViewDefinition universal', pipeline.includes('pipelineSavedViewToUniversal') && pipeline.includes('syncUniversalPipelineViews'))
check('metadata cobre campos usados por views', ['lead.city','lead.source','lead.ownerName','lead.nextActionAt','lead.createdAt','lead.updatedAt'].every((field) => fields.includes(field)))
check('inspector interno de views existe', inspector.includes('__REALTALENT_VIEWS__') && inspector.includes('inspectUniversalViews'))
check('inspector é instalado no bootstrap', main.includes('installUniversalViewInspector()'))
check('testes cobrem AST + adapters', tests.includes('AND/OR/NOT') && tests.includes('contactSavedViewToUniversal') && tests.includes('pipelineSavedViewToUniversal'))
check('testes cobrem colisão de IDs e limpeza de projeção', tests.includes('isola IDs iguais entre superfícies') && tests.includes('replaceSurfaceUniversalViews'))
check('nenhuma migration SQL V101.9.1', !fs.readdirSync(path.join(root, 'supabase/migrations')).some((name) => name.includes('101_9_1')))
check('launcher identifica V101.9.1', launcher.includes('RealTalent CRM V101.9.1 — Universal View Engine'))
check('UX principal não ganhou stylesheet V101.9.1', !fs.readdirSync(path.join(root, 'src/styles')).some((name) => /10191/i.test(name)))
check('release notes existem', exists('RELEASE_NOTES_V101.9.1.md') && read('RELEASE_NOTES_V101.9.1.md').includes('Universal View Engine'))
check('documentação técnica existe', exists('docs/V101.9.1-UNIVERSAL-VIEW-ENGINE.md') && read('docs/V101.9.1-UNIVERSAL-VIEW-ENGINE.md').includes('AND / OR / NOT'))

for (const item of checks) console.log(`${item.ok ? 'OK  ' : 'FAIL'} ${item.label}`)
const failed = checks.filter((item) => !item.ok)
console.log(`\nV101.9.1 Universal View Engine: ${checks.length - failed.length}/${checks.length} contratos aprovados.`)
if (failed.length) {
  console.error(`Falharam: ${failed.map((item) => item.label).join(', ')}`)
  process.exit(1)
}
