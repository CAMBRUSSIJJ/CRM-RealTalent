import fs from 'node:fs'
const read=(p)=>fs.readFileSync(p,'utf8')
const builtins=read('src/platform/extensions/builtin-extensions.ts')
const registry=read('src/platform/extensions/extension-registry.ts')
const commands=read('src/platform/extensions/command-registry.ts')
const permissions=read('src/platform/permissions/permission-engine.ts')
const integration=read('src/services/integration-framework.ts')
const assertions=[];const expect=(label,value)=>assertions.push([label,Boolean(value)])
const ids=[...builtins.matchAll(/id: '(google-workspace|microsoft-365|meta-business|whatsapp-cloud|realtalent-connect|realtalent-capture)'/g)].map((m)=>m[1])
expect('seis manifests nativos únicos',new Set(ids).size===6)
const providerIds=[...builtins.matchAll(/providerId: '(google|microsoft|meta|whatsapp_cloud|realtalent_connect|realtalent_capture)'/g)].map((m)=>m[1])
expect('seis providers únicos',new Set(providerIds).size===6)
expect('Google possui mail + calendar','gmail.readonly'.includes('gmail')&&builtins.includes('google_calendar_pull'))
expect('Microsoft possui mail + calendar',builtins.includes('Mail.Read')&&builtins.includes('microsoft_calendar_pull'))
expect('WhatsApp possui messaging',builtins.includes('whatsapp_business_messaging'))
expect('Connect possui command de chamada',builtins.includes('realtalent_connect.call'))
expect('registry possui proteção contra duplicidade',registry.includes('Provider já registrado'))
expect('command registry possui índice global',commands.includes('commandMap'))
expect('Permission Matrix deriva scopes',permissions.includes('listRegisteredIntegrationScopes'))
expect('Integration Framework deriva provider metadata',integration.includes('providerManifest(provider)'))
expect('lifecycle está ligado a OAuth e sync',integration.includes("'beforeConnect'")&&integration.includes("'beforeSync'"))
for(const [label,ok] of assertions)console.log(`${ok?'OK  ':'FAIL'} ${label}`)
const failed=assertions.filter(([,ok])=>!ok);console.log(`\nExtension Registry smoke: ${assertions.length-failed.length}/${assertions.length}`);if(failed.length)process.exit(1)
